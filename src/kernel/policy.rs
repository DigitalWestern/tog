/// Kinds were spelled with two separators until the names were unified on
/// the hyphen. Policy files and closure records written under the old
/// spellings keep working: every kind is read through `canonical_kind`, so
/// a deny list and a record that disagree about the separator still judge
/// the same way. Nothing writes the left-hand spelling any more.
const LEGACY_KIND_SPELLINGS: &[(&str, &str)] = &[
    ("skipped_optional", SKIPPED_OPTIONAL),
    ("unattested_index", UNATTESTED_INDEX),
    ("lock_disagreement", LOCK_DISAGREEMENT),
    ("unattested_cargo_lock", UNATTESTED_CARGO_LOCK),
    ("artifact_not_provisioned", ARTIFACT_NOT_PROVISIONED),
    ("artifact_provisioned", ARTIFACT_PROVISIONED),
    ("built_from_source", BUILT_FROM_SOURCE),
];

/// Kinds nothing records any more, each with what a record carrying it
/// means now. A deny list may still name one: denying what cannot occur is
/// satisfied by every record, so the entry is dropped rather than refused,
/// and a policy file written for an older tog keeps loading. A closure that
/// still records one is known to be old, not from a newer tog: `tog audit`
/// reports it outdated with the reason here. `toolchain-component-unavailable`
/// was a requested Rust component tog did not ship; tog now provisions
/// every component the pinned release publishes and refuses the rest.
const RETIRED_KINDS: &[(&str, &str)] = &[(
    "toolchain-component-unavailable",
    "closure predates component provisioning",
)];

/// Why a record of `kind` is out of date, when `kind` is one tog retired.
pub fn retired_kind(kind: &str) -> Option<&'static str> {
    RETIRED_KINDS
        .iter()
        .find(|(retired, _)| *retired == canonical_kind(kind))
        .map(|(_, why)| *why)
}

/// The one spelling of `kind` this binary judges, denies, and prints. An
/// unknown kind is returned unchanged: a record from a newer tog must stay
/// unknown rather than be folded into a kind this binary does know.
pub fn canonical_kind(kind: &str) -> &str {
    LEGACY_KIND_SPELLINGS
        .iter()
        .find(|(legacy, _)| *legacy == kind)
        .map_or(kind, |(_, canonical)| *canonical)
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Exception {
    pub kind: String,
    pub subject: String,
    pub detail: String,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Policy {
    #[serde(default)]
    pub strict: bool,
    #[serde(default)]
    pub deny: BTreeSet<String>,
    /// The `[signing]` table. In a parsed file it is what that scope
    /// declared; in a merged chain it is the effective trusted set, `None`
    /// while no machine-scope policy has introduced one. Absent and empty
    /// are different states: absent means "not configured" (an operator
    /// mistake for `tog audit`), empty means "trust nobody".
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub signing: Option<Signing>,
    /// What made this policy strict, and which file denied each kind. Not
    /// part of the file grammar: `serde(skip)` keeps both out of what a
    /// file may set and out of anything this struct is serialized into.
    /// Without them a refusal can name the kind but not the knob that
    /// refused it, which is the difference between an error a reader can
    /// act on and one they cannot.
    #[serde(skip)]
    pub strict_source: Option<StrictSource>,
    #[serde(skip)]
    pub deny_sources: BTreeMap<String, PathBuf>,
}

/// What turned strictness on. A refusal names it, because the fix differs:
/// drop a flag, unset a variable, or edit a file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum StrictSource {
    /// `--strict` on this command line.
    Flag,
    /// `TOG_STRICT=1` in the environment.
    Env,
    /// `strict = true` in this policy file.
    File(PathBuf),
}

impl StrictSource {
    /// The knob, and the literal edit that turns it off.
    fn fix(&self) -> String {
        match self {
            StrictSource::Flag => {
                "--strict refuses every exception kind; rerun without --strict".into()
            }
            StrictSource::Env => {
                "TOG_STRICT=1 refuses every exception kind; unset TOG_STRICT".into()
            }
            StrictSource::File(path) => format!(
                "'strict = true' in {} refuses every exception kind; set \
                 'strict = false' there and name the kinds to refuse in 'deny'",
                path.display()
            ),
        }
    }
}

/// The `[signing]` policy table: the public keys whose closure signatures
/// `tog audit` accepts. Every other command parses it and ignores it.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Signing {
    /// `ed25519:<64 hex>` entries, decoded and deduplicated on the key
    /// bytes. Required: a `[signing]` table that says nothing is refused.
    pub trusted: KeySet,
}

static POLICY: OnceLock<Policy> = OnceLock::new();

#[derive(Debug)]
struct Frame {
    id: u64,
    owner: std::thread::ThreadId,
    ecosystem: String,
    exceptions: Vec<Exception>,
    claimed: bool,
    published: bool,
}

static FRAMES: OnceLock<Mutex<Vec<Frame>>> = OnceLock::new();
static NEXT_FRAME_ID: AtomicU64 = AtomicU64::new(1);

fn frames() -> &'static Mutex<Vec<Frame>> {
    FRAMES.get_or_init(|| Mutex::new(Vec::new()))
}

fn with_frames<R>(f: impl FnOnce(&mut Vec<Frame>) -> R) -> R {
    f(&mut frames().lock().unwrap_or_else(|error| error.into_inner()))
}

/// Parse one policy file, refusing unknown keys and unknown deny kinds.
pub fn parse_file(path: &Path, text: &str) -> io::Result<Policy> {
    let mut policy: Policy = toml::from_str(text).map_err(|e| {
        io::Error::new(
            io::ErrorKind::InvalidData,
            format!("parse {}: {e}", path.display()),
        )
    })?;
    // One spelling from here on: a file may name a kind either way, and
    // what the chain carries is the canonical name.
    policy.deny = policy
        .deny
        .iter()
        .map(|kind| canonical_kind(kind).to_string())
        .filter(|kind| retired_kind(kind).is_none())
        .collect();
    let unknown: Vec<&str> = policy
        .deny
        .iter()
        .map(String::as_str)
        .filter(|kind| !KINDS.contains(kind))
        .collect();
    if !unknown.is_empty() {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            format!(
                "{}: unknown deny kind(s): {}; valid kinds: {}",
                path.display(),
                unknown.join(", "),
                KINDS.join(", ")
            ),
        ));
    }
    Ok(policy)
}

fn merge_file(
    policy: &mut Policy,
    sources: &mut Vec<PolicySource>,
    path: &Path,
    required: bool,
    origin: SourceOrigin,
) -> io::Result<bool> {
    let text = match fs::read_to_string(path) {
        Ok(text) => text,
        Err(e) if e.kind() == io::ErrorKind::NotFound && !required => return Ok(false),
        Err(e) => {
            return Err(io::Error::new(
                e.kind(),
                format!("read {}: {e}", path.display()),
            ))
        }
    };
    merge_text(policy, sources, path, &text, origin)?;
    Ok(true)
}

/// `merge_file` for text already read (the project's own policy, read
/// through the held project descriptor).
fn merge_text(
    policy: &mut Policy,
    sources: &mut Vec<PolicySource>,
    path: &Path,
    text: &str,
    origin: SourceOrigin,
) -> io::Result<()> {
    let other = parse_file(path, text)?;
    // Attribute before merging: after the union nothing says which file
    // asked for a denial, and a refusal has to name the file to fix.
    if other.strict && policy.strict_source.is_none() {
        policy.strict_source = Some(StrictSource::File(path.to_path_buf()));
    }
    for kind in &other.deny {
        policy
            .deny_sources
            .entry(kind.clone())
            .or_insert_with(|| path.to_path_buf());
    }
    merge(policy, &other, origin);
    // Only a file that existed and was merged is a source; the optional
    // files that were not there contributed nothing to attribute.
    sources.push(PolicySource::from_file(origin, path, &other));
    Ok(())
}

#[cfg(unix)]
type PathIdentity = (u64, u64);

#[cfg(not(unix))]
type PathIdentity = PathBuf;

/// Identify an existing path by its filesystem identity. This catches hard
/// links and bind mounts that do not share a pathname.
#[cfg(unix)]
fn path_identity(path: &Path) -> Option<PathIdentity> {
    fs::metadata(path)
        .ok()
        .map(|metadata| (metadata.dev(), metadata.ino()))
}

/// Identify a path by its canonical spelling on platforms without Unix file
/// identity fields.
#[cfg(not(unix))]
fn path_identity(path: &Path) -> Option<PathIdentity> {
    Some(fs::canonicalize(path).unwrap_or_else(|_| path.to_path_buf()))
}

/// Union `other` into `policy`. Union only tightens: the result denies
/// everything `policy` denied plus everything `other` denies, and is strict
/// if either is. Deny and strictness are scope-free, so this ignores the
/// `[signing]` table; `merge` applies it by origin.
pub fn union(policy: &mut Policy, other: &Policy) {
    policy.strict |= other.strict;
    policy.deny.extend(other.deny.iter().cloned());
}

/// Merge one scope's policy into the chain: `union` for deny and
/// strictness, and the origin rule for signing trust. Only the machine
/// scope introduces a trusted set; a project or `--policy` file intersects
/// with it, so a working tree can drop keys but never vouch for its own.
/// A scope with no `[signing]` table leaves the set unchanged, and a
/// project or flag list seen before any machine declaration cannot
/// initialize it: trust stays unconfigured. Used by `tog audit
/// --policy` too, so the file handed to the gate can never loosen the
/// machine or project policy.
pub fn merge(policy: &mut Policy, other: &Policy, origin: SourceOrigin) {
    union(policy, other);
    match origin {
        SourceOrigin::Machine => {
            if let Some(declared) = &other.signing {
                policy.signing = Some(declared.clone());
            }
        }
        SourceOrigin::Project | SourceOrigin::Flag => {
            if let (Some(effective), Some(declared)) = (policy.signing.as_mut(), &other.signing) {
                signing::intersect(&mut effective.trusted, &declared.trusted);
            }
        }
        SourceOrigin::Env => {}
    }
}

/// Where one contributing policy came from. The serialized names
/// (`machine`, `project`, `flag`, `env`) are the stable strings
/// `tog audit --json` reports under `policy.sources`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum SourceOrigin {
    /// `TOG_POLICY`, or `$HOME/.tog/policy.toml` when it is unset.
    Machine,
    /// An ancestor directory's `.tog/policy.toml`.
    Project,
    /// A file named by `tog audit --policy`. Other commands may also use
    /// this origin for their `--strict` flag; audit uses it only for the file.
    Flag,
    /// `TOG_STRICT=1`. Not a file: `path` is absent.
    Env,
}

impl SourceOrigin {
    /// The same lowercase name the serializer writes; a unit test pins the
    /// two together so the report's contract cannot drift.
    pub fn as_str(self) -> &'static str {
        match self {
            SourceOrigin::Machine => "machine",
            SourceOrigin::Project => "project",
            SourceOrigin::Flag => "flag",
            SourceOrigin::Env => "env",
        }
    }
}

impl std::fmt::Display for SourceOrigin {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.as_str())
    }
}

/// One policy that contributed to a merged `Policy`, and what it said.
/// `union` is silent about provenance, so a report that only shows the
/// merged deny set cannot say which file asked for a denial; this is that
/// missing half.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PolicySource {
    pub origin: SourceOrigin,
    /// The file that was read, absent for strictness sources.
    pub path: Option<PathBuf>,
    pub strict: bool,
    pub deny: BTreeSet<String>,
    /// The `[signing] trusted` list this scope declared: `None` when the
    /// file has no `[signing]` table, `Some` (possibly empty) when it does.
    /// Shown per scope so a key the machine does not trust is visible in
    /// the project list that named it.
    pub trusted: Option<KeySet>,
}

impl PolicySource {
    /// The entry for a policy read from `path`, including one merged in
    /// from outside the chain (`tog audit --policy`).
    pub fn from_file(origin: SourceOrigin, path: &Path, policy: &Policy) -> Self {
        Self {
            origin,
            path: Some(path.to_path_buf()),
            strict: policy.strict,
            deny: policy.deny.clone(),
            trusted: policy
                .signing
                .as_ref()
                .map(|signing| signing.trusted.clone()),
        }
    }
}

/// Load the machine and project policies, unioning all deny entries.
pub fn load(project_dir: &Path, cli_strict: bool) -> io::Result<Policy> {
    Ok(load_with_sources(project_dir, cli_strict)?.0)
}

/// `load`, plus every policy that contributed, in merge order. One loading
/// algorithm serves both: `load` is this with the provenance discarded.
/// Callers that pass `cli_strict=true` can produce a `flag` source; audit passes `false` and adds
/// its separately parsed policy file as a source.
pub fn load_with_sources(
    project_dir: &Path,
    cli_strict: bool,
) -> io::Result<(Policy, Vec<PolicySource>)> {
    load_with_sources_from(project_dir, None, cli_strict)
}

/// `load_with_sources` with the project directory itself read through a
/// descriptor the caller holds: its own `.tog/policy.toml` is the one of
/// the directory being synced, whatever its path names by then. Ancestor
/// and machine policies are outside the project and still read by path.
fn load_with_sources_from(
    project_dir: &Path,
    project: Option<&ProjectRoot>,
    cli_strict: bool,
) -> io::Result<(Policy, Vec<PolicySource>)> {
    let mut policy = Policy::default();
    let mut sources = Vec::new();
    let machine_path = if let Some(path) = std::env::var_os("TOG_POLICY") {
        let path = PathBuf::from(path);
        merge_file(
            &mut policy,
            &mut sources,
            &path,
            true,
            SourceOrigin::Machine,
        )?;
        path_identity(&path)
    } else if let Some(home) = std::env::var_os("HOME") {
        let path = PathBuf::from(home).join(".tog/policy.toml");
        let loaded = merge_file(
            &mut policy,
            &mut sources,
            &path,
            false,
            SourceOrigin::Machine,
        )?;
        loaded.then(|| path_identity(&path)).flatten()
    } else {
        None
    };
    // Every ancestor's project policy applies (union only tightens), so a
    // workspace-root policy governs builds started in a member directory
    // without tog having to know each ecosystem's rooting rule.
    for dir in project_dir.ancestors() {
        let path = dir.join(".tog/policy.toml");
        if machine_path
            .as_ref()
            .is_some_and(|machine| path_identity(&path).as_ref() == Some(machine))
        {
            continue;
        }
        if let Some(project) = project.filter(|project| project.path() == dir) {
            // The project's own policy is tog state under `.tog`: read with
            // the strict no-follow walk, so a symlinked `.tog` or policy
            // file is refused rather than read through.
            let own = Path::new(".tog/policy.toml");
            if let Some(bytes) = project.read_file(own)? {
                let text = String::from_utf8(bytes).map_err(|_| {
                    io::Error::new(
                        io::ErrorKind::InvalidData,
                        format!("{} is not valid UTF-8", path.display()),
                    )
                })?;
                merge_text(
                    &mut policy,
                    &mut sources,
                    &path,
                    &text,
                    SourceOrigin::Project,
                )?;
            }
            continue;
        }
        merge_file(
            &mut policy,
            &mut sources,
            &path,
            false,
            SourceOrigin::Project,
        )?;
    }
    apply_requested_strictness(&mut policy, &mut sources, cli_strict);
    Ok((policy, sources))
}

/// Apply the strictness requested outside the policy files: `TOG_STRICT=1`
/// and `--strict` (`cli_strict`). Shared by every loader and by the
/// fallback in `current`, so a policy is never built without them.
fn apply_requested_strictness(
    policy: &mut Policy,
    sources: &mut Vec<PolicySource>,
    cli_strict: bool,
) {
    let env_strict = std::env::var("TOG_STRICT").as_deref() == Ok("1");
    // A file that already set `strict = true` keeps the attribution: it is
    // the source that outlives the command, so dropping --strict or
    // unsetting TOG_STRICT would not lift the refusal and a message that
    // said so would be wrong. Only when no file asked for strictness is
    // the flag or the variable the thing to change, flag first because it
    // is the one on the line the reader just typed.
    // Between the two, the variable outlives the command as well: with
    // both set, dropping --strict leaves TOG_STRICT=1 refusing, so the
    // flag is named only when it is the whole reason.
    if policy.strict_source.is_none() {
        if env_strict {
            policy.strict_source = Some(StrictSource::Env);
        } else if cli_strict {
            policy.strict_source = Some(StrictSource::Flag);
        }
    }
    policy.strict |= cli_strict || env_strict;
    if cli_strict {
        sources.push(PolicySource {
            origin: SourceOrigin::Flag,
            path: None,
            strict: true,
            deny: BTreeSet::new(),
            trusted: None,
        });
    }
    if env_strict {
        sources.push(PolicySource {
            origin: SourceOrigin::Env,
            path: None,
            strict: true,
            deny: BTreeSet::new(),
            trusted: None,
        });
    }
}

/// Whether `--strict` was on the command line. Recorded once by the
/// dispatcher before any verb runs, so every policy load in the process
/// reads the same answer whichever verb loads first.
static REQUESTED_STRICT: OnceLock<bool> = OnceLock::new();

/// Record `--strict` for every policy load in this process. The first call
/// wins, like `POLICY`: the dispatcher calls it once, before any verb, and
/// nothing else should, because a second answer would mean two loads in
/// one process could disagree about the flag.
pub fn request_strict(strict: bool) {
    let _ = REQUESTED_STRICT.set(strict);
}

fn requested_strict() -> bool {
    REQUESTED_STRICT.get().copied().unwrap_or(false)
}

/// Initialize the process policy from the chain above `project_dir` and the
/// recorded `--strict`. Repeated calls keep the first loaded policy.
pub fn init(project_dir: &Path) -> io::Result<()> {
    if POLICY.get().is_none() {
        install(load(project_dir, requested_strict())?);
    }
    Ok(())
}

/// `init` for a project held open as a descriptor (sync): the project's own
/// policy is read through it.
pub fn init_in(project: &ProjectRoot) -> io::Result<()> {
    if POLICY.get().is_none() {
        install(load_with_sources_from(project.path(), Some(project), requested_strict())?.0);
    }
    Ok(())
}

/// Make `policy` the process policy and say under `-v` when it is strict
/// and why, since a strict run refuses things an ordinary one allows.
fn install(policy: Policy) {
    if let Some(line) = strict_trace(&policy) {
        crate::kernel::ui::trace(&line);
    }
    let _ = POLICY.set(policy);
}

/// The `-v` line for a strict policy, naming what made it strict; `None`
/// for a policy that is not.
fn strict_trace(policy: &Policy) -> Option<String> {
    if !policy.strict {
        return None;
    }
    Some(match policy.strict_source.as_ref() {
        Some(StrictSource::Flag) => "policy: strict (--strict)".to_string(),
        Some(StrictSource::Env) => "policy: strict (TOG_STRICT=1)".to_string(),
        Some(StrictSource::File(path)) => format!("policy: strict ({})", path.display()),
        None => "policy: strict".to_string(),
    })
}

/// The process policy. Without an `init` it falls back to the default
/// policy plus the requested strictness, so an early read cannot drop
/// `--strict` or `TOG_STRICT=1`. The fallback still misses the policy
/// files, and it is kept for the rest of the process, so a verb must
/// `init` before anything reads the policy.
fn current() -> &'static Policy {
    POLICY.get_or_init(|| {
        let mut policy = Policy::default();
        apply_requested_strictness(&mut policy, &mut Vec::new(), requested_strict());
        policy
    })
}

/// Is the policy chain in force strict? Strictness refuses every exception
/// kind, and it also refuses to create a file a reviewer has not seen: the
/// toolchain lock is written by an ordinary sync, never by a strict one.
pub fn strict() -> bool {
    current().strict
}

/// Does the policy chain in force declare a `[signing]` table? That table
/// is the only evidence that anyone here cares whether closures are
/// signed, so it is what decides whether an unsigned sync is worth saying
/// anything about.
pub fn signing_configured() -> bool {
    current().signing.is_some()
}

/// Whether `policy` refuses an exception of `kind`.
pub fn denied(policy: &Policy, kind: &str) -> bool {
    policy.strict || policy.deny.contains(canonical_kind(kind))
}

/// The refusal a denied exception prints. It names the kind, the knob that
/// refused it, and the literal edit that would allow it; a reader who has
/// never opened a policy file can act on it without reading one.
pub fn refusal(policy: &Policy, kind: &str, subject: &str, detail: &str) -> String {
    let kind = canonical_kind(kind);
    // Strictness is reported first when both apply: removing the kind from
    // a deny list changes nothing while strict is on.
    let fix = match (policy.strict, policy.deny_sources.get(kind)) {
        (true, _) => match &policy.strict_source {
            Some(source) => source.fix(),
            None => "this policy refuses every exception kind".to_string(),
        },
        (false, Some(path)) => format!(
            "'{kind}' is in the deny list in {}; remove that line to allow it",
            path.display()
        ),
        (false, None) => {
            format!("'{kind}' is in a policy deny list; remove that line to allow it")
        }
    };
    format!("policy denies {kind}: {subject}: {detail}; {fix}")
}

pub fn record_with(policy: &Policy, kind: &str, subject: &str, detail: &str) -> io::Result<()> {
    with_frames(|frames| {
        let Some(frame) = frames.last_mut() else {
            return Err(io::Error::other(
                "exception recorded outside any attribution",
            ));
        };
        // Records belong to the thread that opened the innermost frame. A
        // worker thread recording into another realization's frame would be
        // claimed by that realization's closure.
        if frame.owner != std::thread::current().id() {
            return Err(io::Error::other(format!(
                "exception {kind} recorded from a thread that does not own the {} attribution",
                frame.ecosystem
            )));
        }
        if denied(policy, kind) {
            return Err(io::Error::new(
                io::ErrorKind::PermissionDenied,
                refusal(policy, kind, subject, detail),
            ));
        }
        let kind = canonical_kind(kind);
        // The record itself is progress: what to do about it depends on
        // whether a policy gate exists, which the end-of-sync summary
        // (`commands::sync::exception_summary`) knows and this frame does not.
        ui::note(&format!("exception {kind}: {subject}: {detail}"));
        frame.exceptions.push(Exception {
            kind: kind.into(),
            subject: subject.into(),
            detail: detail.into(),
        });
        Ok(())
    })
}

pub fn record(kind: &str, subject: &str, detail: &str) -> io::Result<()> {
    record_with(current(), kind, subject, detail)
}

fn format_exception_list(exceptions: &[Exception]) -> String {
    exceptions
        .iter()
        .map(|exception| {
            format!(
                "{}: {}: {}",
                exception.kind, exception.subject, exception.detail
            )
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// A value that owns one frame in the process-global attribution stack.
#[must_use = "an attribution must be held across the realization it owns"]
#[derive(Debug)]
pub struct Attribution {
    id: u64,
    ecosystem: String,
    active: bool,
}

impl Attribution {
    /// Open a realization frame. A different thread may not open over the
    /// current innermost frame because records are process-global.
    pub fn open(ecosystem: &str) -> io::Result<Self> {
        let owner = std::thread::current().id();
        with_frames(|frames| {
            if let Some(frame) = frames.last() {
                if frame.owner != owner {
                    return Err(io::Error::new(
                        io::ErrorKind::WouldBlock,
                        format!(
                            "another thread owns the innermost attribution for {}; {ecosystem} cannot open",
                            frame.ecosystem
                        ),
                    ));
                }
            }
            let id = NEXT_FRAME_ID.fetch_add(1, Ordering::Relaxed);
            frames.push(Frame {
                id,
                owner,
                ecosystem: ecosystem.to_string(),
                exceptions: Vec::new(),
                claimed: false,
                published: false,
            });
            Ok(Self {
                id,
                ecosystem: ecosystem.to_string(),
                active: true,
            })
        })
    }

    /// Open a child realization owned by this token's thread. Records while
    /// it is open belong to the child and cannot be claimed by the parent.
    pub fn nested(&mut self, ecosystem: &str) -> io::Result<Self> {
        let owner = std::thread::current().id();
        with_frames(|frames| {
            let Some(parent) = frames.last() else {
                return Err(io::Error::other(
                    "cannot nest attribution without an open frame",
                ));
            };
            if parent.id != self.id {
                return Err(io::Error::other(
                    "cannot nest attribution while another child frame is open",
                ));
            }
            if parent.owner != owner {
                return Err(io::Error::new(
                    io::ErrorKind::WouldBlock,
                    "cannot nest attribution from another thread",
                ));
            }
            let id = NEXT_FRAME_ID.fetch_add(1, Ordering::Relaxed);
            frames.push(Frame {
                id,
                owner,
                ecosystem: ecosystem.to_string(),
                exceptions: Vec::new(),
                claimed: false,
                published: false,
            });
            Ok(Self {
                id,
                ecosystem: ecosystem.to_string(),
                active: true,
            })
        })
    }

    pub fn ecosystem(&self) -> &str {
        &self.ecosystem
    }

    /// The exceptions recorded into this frame so far, without claiming
    /// them. For diagnostics and tests; publication goes through `claim`.
    pub fn recorded(&self) -> Vec<Exception> {
        with_frames(|frames| {
            frames
                .iter()
                .find(|frame| frame.id == self.id)
                .map(|frame| frame.exceptions.clone())
                .unwrap_or_default()
        })
    }

    /// Claim the innermost frame for one closure. Only the comforter writer
    /// calls this at the publication boundary; a claimed frame must then be
    /// published or it cannot finish.
    pub(crate) fn claim(&mut self, ecosystem: &str) -> io::Result<Vec<Exception>> {
        with_frames(|frames| {
            let Some(frame) = frames.last_mut() else {
                return Err(io::Error::other(
                    "closure publication outside any attribution",
                ));
            };
            if frame.id != self.id {
                return Err(io::Error::other(
                    "cannot claim attribution while a child frame is open",
                ));
            }
            if ecosystem != self.ecosystem || ecosystem != frame.ecosystem {
                return Err(io::Error::other(format!(
                    "attribution ecosystem mismatch: token is {}, closure is {ecosystem}",
                    self.ecosystem
                )));
            }
            if frame.claimed {
                return Err(io::Error::other(format!(
                    "the {ecosystem} attribution was already claimed"
                )));
            }
            frame.claimed = true;
            Ok(std::mem::take(&mut frame.exceptions))
        })
    }

    /// Mark a successfully written closure. Claiming happens before the
    /// write, so a failed write loses the claimed exceptions with the frame.
    pub(crate) fn mark_published(&mut self) -> io::Result<()> {
        with_frames(|frames| {
            let Some(frame) = frames.last_mut() else {
                return Err(io::Error::other("attribution frame is no longer open"));
            };
            if frame.id != self.id || !frame.claimed {
                return Err(io::Error::other(
                    "attribution cannot be published before its closure is claimed",
                ));
            }
            frame.published = true;
            Ok(())
        })
    }

    pub fn finish(mut self, expect_publication: bool) -> io::Result<()> {
        let result = with_frames(|frames| {
            let Some(index) = frames.iter().position(|frame| frame.id == self.id) else {
                return Err(io::Error::other("attribution frame is no longer open"));
            };
            if index + 1 != frames.len() {
                let result = Err(io::Error::other(
                    "attribution cannot finish while a child frame is open",
                ));
                frames.remove(index);
                return result;
            }
            let frame = frames.last().expect("frame index is valid");
            let result = if frame.claimed && !frame.published {
                Err(io::Error::other(format!(
                    "{} realization claimed its exceptions but the closure write did not complete",
                    self.ecosystem
                )))
            } else if expect_publication && !frame.published {
                Err(io::Error::other(format!(
                    "{} realization reported success but published no closure",
                    self.ecosystem
                )))
            } else if !frame.exceptions.is_empty() {
                Err(io::Error::other(format!(
                    "{} realization ended with {} exception(s) never claimed by a closure: {}",
                    self.ecosystem,
                    frame.exceptions.len(),
                    format_exception_list(&frame.exceptions)
                )))
            } else {
                Ok(())
            };
            frames.pop();
            result
        });
        self.active = false;
        result
    }

    pub fn discard(mut self) {
        with_frames(|frames| {
            if let Some(index) = frames.iter().position(|frame| frame.id == self.id) {
                frames.remove(index);
            }
        });
        self.active = false;
    }
}

impl Drop for Attribution {
    fn drop(&mut self) {
        if !self.active {
            return;
        }
        // Error and panic cleanup. The success path must call finish or
        // discard explicitly, so it cannot silently bypass publication.
        with_frames(|frames| {
            if let Some(index) = frames.iter().position(|frame| frame.id == self.id) {
                frames.remove(index);
            }
        });
    }
}

