    /// The Go module triplet: a record missing only the cached `go.mod`
    /// digest (or the zip or the info file) is truncated, and certifying it
    /// frees the lost cache file of a rooted object.
    #[test]
    fn go_modcache_missing_one_triplet_field_refuses() {
        let artifact = sha256('4');
        let go = go_record("1.25.3", &artifact);
        let extractor = format!("go1.25.3:{artifact}");
        let (zip, modfile, info) = (sha256('5'), sha256('6'), sha256('7'));
        let mod_entry = format!("h1:AbCd=:{zip}");
        let modfile_entry = format!("h1:EfGh=:{modfile}");
        let full = vec![
            ("schema", "go-modcache/1"),
            ("extractor", extractor.as_str()),
            ("mod:golang.org/x/net@v0.1.0", mod_entry.as_str()),
            ("modfile:golang.org/x/net@v0.1.0", modfile_entry.as_str()),
            ("info:golang.org/x/net@v0.1.0", info.as_str()),
        ];
        for key in [
            "mod:golang.org/x/net@v0.1.0",
            "modfile:golang.org/x/net@v0.1.0",
        ] {
            let mut inputs: Vec<(String, String)> = full
                .iter()
                .map(|(k, v)| (k.to_string(), v.to_string()))
                .collect();
            inputs.retain(|(k, _)| k != key);
            let reason = unresolved(
                Identity {
                    kind: "go-modcache".into(),
                    name: "modcache".into(),
                    version: "1".into(),
                    inputs: inputs.into_iter().collect(),
                },
                vec![go.clone()],
            );
            assert!(
                reason.contains(key),
                "deleting {key} did not name it: {reason}"
            );
        }
    }

