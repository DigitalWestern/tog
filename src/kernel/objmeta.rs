    // -- Per-field grammar enforcement -------------------------------------
    //
    // Regression tests for the per-field containment extension: an adapter
    // may certify only complete records. Deleting any required field of a
    // real producer layout, or carrying an unrecognized input, must refuse —
    // never certify a partial set. The table pins the full required grammar
    // for each dispatch row.

    /// Adapt `identity` against `others` after deleting input `key`.
    fn adapt_without(record: &Record, key: &str, others: Vec<Record>) -> Adaptation {
        let mut identity = record.identity.clone();
        identity.inputs.remove(key);
        adapt_identity_for_test(identity, others)
    }

    /// Full identities for one dispatch row each, paired with the required
    /// input keys the grammar table demands. Deleting each key must produce
    /// an `Unresolved` that names it.
    #[test]
    fn deleting_any_required_input_of_a_real_layout_refuses() {
        let sdk = oid('b', "dotnet-sdk");
        let rust = oid('b', "rust");
        let beam = legacy_record(beam_identity(true).0);
        let artifact4 = sha256('4');
        let go = go_record("1.25.3", &artifact4);
        let rows: Vec<(Record, Vec<Record>, Vec<&str>)> = vec![
            // cpython (kind without a schema input)
            (
                legacy_record(ident(
                    "cpython",
                    "cpython",
                    "3.11.9",
                    &[
                        ("artifact_sha256", &sha256('1')),
                        ("platform", "x86_64-unknown-linux-gnu"),
                    ],
                )),
                vec![],
                vec!["artifact_sha256"],
            ),
            // dotnet-sdk/1
            (
                legacy_record(ident(
                    "dotnet-sdk",
                    "dotnet-sdk",
                    "10.0.100",
                    &[
                        ("schema", "dotnet-sdk/1"),
                        ("artifact_sha512", &sha512('a')),
                        ("platform", "x86_64-unknown-linux-gnu"),
                    ],
                )),
                vec![],
                vec!["schema", "artifact_sha512"],
            ),
            // git-source/2
            (
                legacy_record(ident(
                    "git-source",
                    "github.com-owner-repo",
                    "deadbeef",
                    &[
                        ("schema", "git-source/2"),
                        ("url", "https://github.com/owner/repo"),
                        ("commit", "deadbeef"),
                    ],
                )),
                vec![],
                vec!["schema", "url", "commit"],
            ),
            // rustfmt/1
            (
                legacy_record(ident(
                    "rustfmt",
                    "rustfmt",
                    "1.90.0",
                    &[
                        ("schema", "rustfmt/1"),
                        ("platform", "x86_64-unknown-linux-gnu"),
                        ("rust_object", &rust),
                        ("rustfmt_sha256", &sha256('c')),
                    ],
                )),
                vec![stub(&rust)],
                vec!["schema", "rust_object", "rustfmt_sha256"],
            ),
            // nuget-packages/1
            (
                legacy_record(ident(
                    "nuget-packages",
                    "packages",
                    "1",
                    &[
                        ("schema", "nuget-packages/1"),
                        ("extractor", &sdk),
                        ("pkg:newtonsoft.json@13.0.3", "hOtwCFbUpsnhVvBFuG3lXQ=="),
                        ("raw:newtonsoft.json@13.0.3", &sha256('e')),
                    ],
                )),
                vec![stub(&sdk)],
                vec!["schema", "extractor"],
            ),
            // go-toolchain/1
            (go.clone(), vec![], vec!["schema", "artifact_sha256"]),
            // sdist-build/2
            (
                legacy_record(sdist_v2_identity(
                    "widget",
                    &sha256('2'),
                    &format!("3.11.9:{}", sha256('1')),
                    &sha256('3'),
                )),
                vec![cpython_record(
                    "3.11.9",
                    &sha256('1'),
                    "x86_64-unknown-linux-gnu",
                )],
                vec!["schema", "sdist_sha256", "python", "platform", "toolchain"],
            ),
            // hex-deps/1
            (
                legacy_record(hex_deps_row_identity(&beam_fingerprint_of(&beam).unwrap())),
                vec![beam],
                vec!["schema", "beam"],
            ),
        ];
        for (record, others, required) in &rows {
            // Sanity: the complete record is certified, so the refusals
            // below are caused by the deleted field, not the fixture.
            assert!(
                matches!(
                    adapt_identity_for_test(record.identity.clone(), others.clone()),
                    Adaptation::Proven(_)
                ),
                "the complete {} record did not certify",
                record.identity.kind
            );
            for key in required {
                match adapt_without(record, key, others.clone()) {
                    Adaptation::Unresolved(reason) => assert!(
                        reason.contains(key),
                        "deleting {key} of {} did not name it: {reason}",
                        record.identity.kind
                    ),
                    Adaptation::Proven(_) => panic!(
                        "deleting required input {key} of {} still certified a complete set",
                        record.identity.kind
                    ),
                }
            }
        }
    }

