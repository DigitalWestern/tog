    fn beam_inputs(relocation: bool) -> (Vec<(String, String)>, String) {
        let (otp, elixir, hex_ez, rebar3) = (sha256('1'), sha256('2'), sha512('3'), sha512('4'));
        let mut inputs = vec![
            ("schema".to_string(), "beam-toolchain/1".to_string()),
            ("otp_sha256".to_string(), otp.clone()),
            ("elixir_sha256".to_string(), elixir.clone()),
            ("hex_sha512".to_string(), hex_ez.clone()),
            ("rebar3_sha512".to_string(), rebar3.clone()),
            ("versions".to_string(), "hex2.5.1:rebar3.25.1".to_string()),
            (
                "platform".to_string(),
                "x86_64-unknown-linux-gnu".to_string(),
            ),
        ];
        let joined = if relocation {
            inputs.push((
                "relocation_schema".to_string(),
                "beam-relocate/1".to_string(),
            ));
            inputs.push(("store_root".to_string(), "/tmp/store".to_string()));
            format!("{otp}:{elixir}:{hex_ez}:{rebar3}:beam-relocate/1")
        } else {
            format!("{otp}:{elixir}:{hex_ez}:{rebar3}")
        };
        (
            inputs,
            crate::tailors::elixir::fingerprint_of_joined(&joined),
        )
    }

