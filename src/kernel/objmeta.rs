//! Object metadata: the `object-meta/2` record, its read-only index, and the
//! pure per-kind/per-schema adapters that upgrade a legacy record.
//!
//! An adapter is a pure function of one validated legacy record plus a
//! read-only index of the other records in the store. It returns
//! `Proven(ObjectDeps)` — the exact set the producer of that record would
//! supply today — or `Unresolved(reason)`. It never reads the network, never
//! runs a package manager or a build, and never falls back on a current
//! default pin: everything it certifies is derived from the record's own
//! identity inputs, or from another record it matched exactly.
//!
//! The old inferred `refs` array is never evidence of completeness. It was
//! generated by scanning identity inputs for anything that looked like an
//! object id (`store::object_refs`), so it can be both incomplete (an
//! indirect reference recorded as a fingerprint) and over-broad. Adapters
//! reconstruct the set from the producer's own input grammar instead.
//!
//! Each row also carries a separate live grammar used only by debug builds at
//! publication time. The migration grammar remains compatible with records
//! made by older producers.

use crate::kernel::fetch::Digest;
use crate::kernel::platform::Platform;
use crate::kernel::store::{self, ObjectDeps};
use crate::kernel::types::Identity;
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::io;
use std::path::Path;
use std::sync::OnceLock;

/// The result of adapting one legacy record.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Adaptation {
    /// The exact dependency set the producer would supply for this identity.
    Proven(ObjectDeps),
    /// The record cannot be certified. The string names the kind, the schema
    /// and what is missing, so the operator can act on it.
    Unresolved(String),
}

/// What a stored record claims about how its dependency set was obtained.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Evidence {
    /// Pre-`object-meta/2`: no dependency evidence at all.
    Legacy,
    /// Supplied by the realization caller at commit time.
    Explicit,
    /// Derived from a legacy record by the named adapter version.
    Adapted(String),
}

/// One parsed metadata record. Reading never touches object mtimes.
#[derive(Debug, Clone)]
pub struct Record {
    pub id: String,
    pub identity: Identity,
    pub evidence: Evidence,
    /// Empty for a legacy record: it has no proven dependencies.
    pub dependencies: BTreeSet<String>,
    pub cache: BTreeSet<Digest>,
    /// The legacy record carried a `refs` array. This is *not* completeness
    /// evidence; it is the legacy retention boundary that `--collect-legacy`
    /// keys on, and migration must preserve it.
    pub had_legacy_refs: bool,
    /// The whole record, so migration can rewrite it without inventing or
    /// dropping unrelated fields (`created`, `exceptions`, ...).
    pub value: serde_json::Value,
}

/// The `schema` input an identity dispatches on, if it wrote one. The
/// migration path (`Record::schema_input`) and the commit-time drift check
/// share this one reader so a pair can never be looked up two different ways.
pub(crate) fn schema_input_of(identity: &Identity) -> Option<&str> {
    identity.inputs.get("schema").map(String::as_str)
}

/// Parse the platform identity input once for live contracts. A malformed
/// platform is a producer bug even when the row only uses it to choose a
/// conditional input shape.
pub(crate) fn platform_of(identity: &Identity) -> Result<Option<Platform>, String> {
    let Some(value) = identity.inputs.get("platform") else {
        return Ok(None);
    };
    Platform::ALL
        .iter()
        .copied()
        .find(|platform| platform.triple() == value)
        .map(Some)
        .ok_or_else(|| format!("identity has an unparseable platform input {value:?}"))
}

impl Record {
    pub fn schema_input(&self) -> Option<&str> {
        schema_input_of(&self.identity)
    }

    /// The kind/schema pair used for adapter dispatch and for diagnostics.
    /// Kinds whose producer never wrote a `schema` input dispatch on the
    /// kind alone; they are listed explicitly in `adapt` so a record that
    /// unexpectedly carries one is refused instead of silently sharing a
    /// path with a different schema.
    pub fn describe(&self) -> String {
        match self.schema_input() {
            Some(schema) => format!("kind {}, schema {schema}", self.identity.kind),
            None => format!("kind {}, no schema input", self.identity.kind),
        }
    }
}

/// A read-only index of every metadata record in the store.
///
/// Adapters use it to resolve indirect references: a producer often commits a
/// *fingerprint* of another object (a version/digest pair, a truncated hash)
/// rather than its id, and the only sound way back to the id is to find the
/// one record whose own identity produces that fingerprint. A missing or
/// ambiguous match is an error, never a guess.
#[derive(Debug, Default, Clone)]
pub struct MetaIndex {
    entries: BTreeMap<String, Record>,
}

impl MetaIndex {
    /// Read and validate every `meta/<id>.json`. Purely a read: no mtime is
    /// refreshed and no object directory is opened.
    ///
    /// This is the strict reader the sweep uses: a single record it cannot
    /// parse stops everything, because a record nothing can read cannot
    /// prove what the object it describes still needs.
    pub fn read(store: &store::Store) -> io::Result<MetaIndex> {
        read_index(store, None)
    }

    /// Read every record, skipping the ones that are structurally unusable
    /// and reporting them as `meta file name -> reason`.
    ///
    /// Migration and `--drop-object` have to *talk about* a record nothing
    /// can parse, so neither can use the strict reader: refusing to read the
    /// store is exactly what leaves an operator with no way out. This
    /// relaxes nothing for the sweep, which still goes through `read`.
    pub fn read_reporting_unusable(
        store: &store::Store,
    ) -> io::Result<(MetaIndex, BTreeMap<String, String>)> {
        let mut unusable = BTreeMap::new();
        let index = read_index(store, Some(&mut unusable))?;
        Ok((index, unusable))
    }

    pub fn get(&self, id: &str) -> Option<&Record> {
        self.entries.get(id)
    }

    pub fn iter(&self) -> impl Iterator<Item = (&String, &Record)> {
        self.entries.iter()
    }

    pub fn len(&self) -> usize {
        self.entries.len()
    }

    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    pub fn contains(&self, id: &str) -> bool {
        self.entries.contains_key(id)
    }

    /// Apply proposed upgrades in memory.
    ///
    /// A dry run must plan from exactly the records a real sweep would have
    /// published, so it carries its unwritten upgrades forward through this
    /// method instead of re-reading the still-legacy files. The real sweep
    /// applies the same overlay over records it has just written, which is a
    /// no-op — that is the point: one code path, one set of evidence.
    pub fn apply(&mut self, upgrades: &BTreeMap<String, serde_json::Value>) -> io::Result<()> {
        for (id, value) in upgrades {
            let record = read_record_value(id, value.clone())?;
            self.entries.insert(id.clone(), record);
        }
        Ok(())
    }

    /// Does the store hold any record that is not already `object-meta/2`?
    pub fn has_legacy(&self) -> bool {
        self.entries
            .values()
            .any(|record| record.evidence == Evidence::Legacy)
    }

    /// The single record of `kind` whose identity satisfies `predicate`.
    ///
    /// Zero matches and more than one match are both errors: an adapter may
    /// not pick a winner, because picking the wrong one certifies a
    /// dependency set that would let GC delete the object actually in use.
    pub(crate) fn unique(
        &self,
        kind: &str,
        what: &str,
        predicate: impl Fn(&Record) -> bool,
    ) -> Result<String, String> {
        let mut found: Vec<&str> = self
            .entries
            .values()
            .filter(|record| record.identity.kind == kind && predicate(record))
            .map(|record| record.id.as_str())
            .collect();
        found.sort_unstable();
        match found.len() {
            1 => Ok(found[0].to_string()),
            0 => Err(format!(
                "no {kind} object in this store matches {what}; the historical build input was \
                 collected by an older sweep and cannot be recovered from metadata"
            )),
            n => Err(format!(
                "{n} {kind} objects match {what} ({}); the reference is ambiguous and must not be guessed",
                found.join(", ")
            )),
        }
    }
}

/// The one directory walk both index readers share, so a record can never be
/// understood one way by the sweep and another way by maintenance.
///
/// `unusable` is the only difference between them. When it is `Some`, a
/// record `read_record_at` rejects as malformed is recorded there and left
/// out of the index; when it is `None`, the same rejection stops the read.
/// An I/O error that is not about a record's content always stops the read,
/// in both modes: a `meta` directory that cannot be listed is not a record
/// an operator can drop.
fn read_index(
    store: &store::Store,
    mut unusable: Option<&mut BTreeMap<String, String>>,
) -> io::Result<MetaIndex> {
    let meta_dir = store.root.join("meta");
    let stat = fs::symlink_metadata(&meta_dir)?;
    if stat.file_type().is_symlink() || !stat.is_dir() {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            "meta is not a real directory",
        ));
    }
    let mut entries = BTreeMap::new();
    for entry in fs::read_dir(&meta_dir)? {
        let entry = entry?;
        let path = entry.path();
        if path.extension().and_then(|ext| ext.to_str()) != Some("json") {
            continue;
        }
        let error = match read_record_at(&path) {
            Ok(record) => {
                entries.insert(record.id.clone(), record);
                continue;
            }
            Err(error) => error,
        };
        let Some(unusable) = unusable.as_deref_mut() else {
            // Strict mode. Every refusal names the record and both commands
            // that end the deadlock: one lists every other unusable record
            // in a single pass, the other removes a record that cannot be
            // repaired.
            return Err(io::Error::new(
                error.kind(),
                format!(
                    "{error}; nothing can be swept until this record is usable. Run `tog gc \
                     --migrate-metadata` to list every unusable record, then drop the ones \
                     you cannot repair with `tog gc --drop-object <id>` (the next sync \
                     rebuilds the object)"
                ),
            ));
        };
        if error.kind() != io::ErrorKind::InvalidData {
            // A read that failed for a reason other than the record's own
            // content — a permission, a vanished file — is returned bare.
            // The advice above names `--migrate-metadata`, and in lenient
            // mode that is usually the command already running: telling an
            // operator to rerun the thing that just failed is worse than
            // telling them nothing.
            return Err(error);
        }
        let name = entry.file_name().to_string_lossy().into_owned();
        unusable.insert(name, error.to_string());
    }
    Ok(MetaIndex { entries })
}

/// Parse and validate one metadata file. Shared by the index and by the
/// sweep reader so a record can never be understood two different ways.
pub fn read_record_at(path: &Path) -> io::Result<Record> {
    let stat = fs::symlink_metadata(path)?;
    if stat.file_type().is_symlink() || !stat.is_file() {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            format!("object metadata {} is not a regular file", path.display()),
        ));
    }
    let id = path
        .file_stem()
        .and_then(|stem| stem.to_str())
        .ok_or_else(|| {
            io::Error::new(
                io::ErrorKind::InvalidData,
                format!("object metadata name {} is not UTF-8", path.display()),
            )
        })?
        .to_string();
    if !store::is_object_id(&id) {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            format!("object metadata id {id:?} is malformed"),
        ));
    }
    let value: serde_json::Value =
        serde_json::from_reader(fs::File::open(path)?).map_err(|error| {
            io::Error::new(
                io::ErrorKind::InvalidData,
                format!("parse object metadata {}: {error}", path.display()),
            )
        })?;
    read_record_value(&id, value)
}

/// Validate an already-parsed record body against its id.
pub fn read_record_value(id: &str, value: serde_json::Value) -> io::Result<Record> {
    let bad = |message: String| io::Error::new(io::ErrorKind::InvalidData, message);
    let identity_value = value
        .get("identity")
        .cloned()
        .ok_or_else(|| bad(format!("object {id} metadata has no identity")))?;
    let identity: Identity = serde_json::from_value(identity_value)
        .map_err(|error| bad(format!("object {id} has malformed identity: {error}")))?;
    if identity.kind.is_empty() {
        return Err(bad(format!("object {id} metadata has no identity kind")));
    }
    if identity.object_id() != id {
        return Err(bad(format!(
            "object {id} identity hashes to a different object id"
        )));
    }
    if let Some(stored) = value.get("id") {
        if stored.as_str() != Some(id) {
            return Err(bad(format!("object metadata {id} has a mismatched id")));
        }
    }

    let Some(schema_value) = value.get("schema") else {
        // A pre-object-meta/2 record. `refs` is read only to preserve the
        // legacy retention boundary; it is never dependency evidence.
        let had_legacy_refs = value.get("refs").is_some();
        if let Some(refs) = value.get("refs") {
            let refs = refs
                .as_array()
                .ok_or_else(|| bad(format!("object {id} legacy refs is not an array")))?;
            for reference in refs {
                reference
                    .as_str()
                    .ok_or_else(|| bad(format!("object {id} legacy refs contains a non-string")))?;
            }
        }
        return Ok(Record {
            id: id.to_string(),
            identity,
            evidence: Evidence::Legacy,
            dependencies: BTreeSet::new(),
            cache: BTreeSet::new(),
            had_legacy_refs,
            value,
        });
    };

    let schema = schema_value
        .as_str()
        .ok_or_else(|| bad(format!("object {id} has an invalid metadata schema")))?;
    if schema != "object-meta/2" {
        return Err(bad(format!(
            "object {id} has unknown metadata schema {schema}"
        )));
    }
    let mut dependencies = BTreeSet::new();
    for dependency in value
        .get("dependencies")
        .and_then(serde_json::Value::as_array)
        .ok_or_else(|| bad(format!("object {id} metadata has no explicit dependencies")))?
    {
        let dependency = dependency
            .as_str()
            .ok_or_else(|| bad(format!("object {id} has a non-string dependency")))?;
        if !store::is_object_id(dependency) || !dependencies.insert(dependency.to_string()) {
            return Err(bad(format!(
                "object {id} has a malformed or duplicate dependency {dependency:?}"
            )));
        }
    }
    let mut cache = BTreeSet::new();
    for digest in value
        .get("cache_digests")
        .and_then(serde_json::Value::as_array)
        .ok_or_else(|| {
            bad(format!(
                "object {id} metadata has no explicit cache digests"
            ))
        })?
    {
        let object = digest
            .as_object()
            .ok_or_else(|| bad(format!("object {id} has a malformed cache digest")))?;
        let algo = object
            .get("algo")
            .and_then(serde_json::Value::as_str)
            .ok_or_else(|| bad(format!("object {id} cache digest has no algorithm")))?;
        let hex = object
            .get("hex")
            .and_then(serde_json::Value::as_str)
            .ok_or_else(|| bad(format!("object {id} cache digest has no hex")))?;
        let digest = parse_digest(algo, hex)
            .map_err(|reason| bad(format!("object {id} cache digest: {reason}")))?;
        if !cache.insert(digest) {
            return Err(bad(format!("object {id} has a duplicate cache digest")));
        }
    }
    let evidence = value
        .get("evidence")
        .and_then(serde_json::Value::as_str)
        .ok_or_else(|| bad(format!("object {id} metadata has no evidence marker")))?;
    let evidence = if evidence == "explicit" {
        Evidence::Explicit
    } else if let Some(rest) = evidence.strip_prefix("adapted:") {
        if rest.is_empty() {
            return Err(bad(format!("object {id} has an empty adapted marker")));
        }
        Evidence::Adapted(rest.to_string())
    } else {
        return Err(bad(format!(
            "object {id} has unknown evidence marker {evidence}"
        )));
    };
    // Migration preserves the legacy retention boundary explicitly: a record
    // that never carried `refs` keeps its legacy retention after upgrade,
    // because proving an object's outgoing dependencies says nothing about
    // whether some pre-registry project still needs the object itself.
    let had_legacy_refs = evidence == Evidence::Explicit
        || !value
            .get("legacy_retention")
            .and_then(serde_json::Value::as_bool)
            .unwrap_or(false);
    Ok(Record {
        id: id.to_string(),
        identity,
        evidence,
        dependencies,
        cache,
        had_legacy_refs,
        value,
    })
}

pub(crate) fn parse_digest(algo: &str, hex: &str) -> Result<Digest, String> {
    let digest = match algo {
        "sha1" => Digest::sha1(hex),
        "sha256" => Digest::sha256(hex),
        "sha512" => Digest::sha512(hex),
        other => return Err(format!("unsupported cache algorithm {other}")),
    };
    digest.map_err(|error| error.to_string())
}

// ---------------------------------------------------------------------------
// Adapters
//
// Each adapter reconstructs the dependency set the producer of that record
// builds today, from the producer's own input grammar. The pairing is
// deliberate: `adapt` must return exactly what `commit_with_deps` would be
// given for the same identity, or a migrated store stops being syncable —
// `store::validate_cached_dependency_evidence` turns every later cache hit on
// a divergent record into a hard error.
//
// The coverage matrix in ARCHITECTURE.md lists every row implemented here.
// ---------------------------------------------------------------------------

/// The adapter version stamped into `evidence: "adapted:<kind>@<version>"`.
/// Bump a kind's version when its reconstruction changes meaning, so an old
/// adapted record is distinguishable from a new one.
pub fn adapter_version(_kind: &str) -> u32 {
    1
}

/// Adapt one legacy record. Pure: the only inputs are the record and the
/// index, and the only outputs are a proven set or a named reason.
pub fn adapt(record: &Record, index: &MetaIndex) -> Adaptation {
    if record.evidence != Evidence::Legacy {
        return Adaptation::Unresolved(format!(
            "{}: record is already object-meta/2 and is not a migration candidate",
            record.describe()
        ));
    }
    match adapt_inner(record, index) {
        Ok(deps) => Adaptation::Proven(deps),
        Err(reason) => Adaptation::Unresolved(format!("{}: {reason}", record.describe())),
    }
}

/// The migration input grammar for a (kind, schema) pair.
///
/// `required` inputs are written unconditionally at every commit; `optional`
/// inputs are written only in some shapes. Anything else must match one of
/// `groups`' prefixes. A record that misses a required input, carries an
/// unrecognized input, or breaks a group's pairing is incomplete evidence and
/// is refused — the same conservative principle as the containment guard,
/// applied per field: never certify less than the producer demonstrably
/// wrote.
#[derive(Clone, Copy)]
pub struct Grammar {
    pub required: &'static [&'static str],
    pub optional: &'static [&'static str],
    /// Recognized dynamic key prefixes. Each entry may demand sibling
    /// prefixes for the same suffix (`("raw:", Some(&["pkg:"]))` means every
    /// `raw:<name>` input requires a `pkg:<name>` input and vice versa).
    pub groups: &'static [(&'static str, Option<&'static [&'static str]>)],
}

/// One (kind, schema) pair a producer writes: its live publication grammar,
/// migration grammar, and the function that recovers a legacy record's
/// dependency set. Tailors own their rows (`Tailor::object_kinds`); the kernel
/// owns `git-source`.
pub struct KindAdapter {
    pub kind: &'static str,
    pub schema: Option<&'static str>,
    /// The schema value that replaced this one, for a row no producer writes
    /// any more. A superseded row stays registered so legacy records of the
    /// old layout still migrate and their objects are swept as ordinary
    /// garbage rather than blocking every sweep; publishing one is refused,
    /// so a producer cannot quietly keep minting the retired identity.
    pub superseded_by: Option<&'static str>,
    /// Inputs required from the current producer at every commit. These are
    /// separate from `grammar.required`, which preserves legacy compatibility.
    pub live_required: &'static [&'static str],
    /// Inputs the current producer may add conditionally. Entries ending in
    /// `:` are recognized prefixes, such as `pkg:` for variable package keys.
    pub live_optional: &'static [&'static str],
    /// Inputs retained only for legacy records. Each entry needs a comment in
    /// the owning row explaining why the current producer no longer writes it.
    pub legacy_only: &'static [&'static str],
    /// The full producer-owned identity contract. It runs after the generic
    /// required-name, whitelist, unknown-kind and schema checks.
    pub live_contract: Option<fn(&Identity) -> Result<(), String>>,
    pub grammar: Grammar,
    pub adapt: fn(&Record, &MetaIndex) -> Result<ObjectDeps, String>,
}

/// The kernel's own kinds: sources realized by the kernel, not a tailor.
static KERNEL_KINDS: &[KindAdapter] = &[KindAdapter {
    kind: "git-source",
    schema: Some("git-source/2"),
    superseded_by: None,
    live_required: &["schema", "url", "commit"],
    live_optional: &[],
    legacy_only: &[],
    live_contract: None,
    grammar: Grammar {
        required: &["schema", "url", "commit"],
        optional: &[],
        groups: &[],
    },
    adapt: no_dependencies,
}];

/// Synthetic objects are useful to kernel and comforter unit tests, but an
/// arbitrary kind must never pass the live publication check. Keep their
/// registration test-only so production can only commit a shipped row.
#[cfg(test)]
static TEST_KINDS: &[KindAdapter] = &[KindAdapter {
    kind: "test",
    schema: None,
    superseded_by: None,
    live_required: &[],
    live_optional: &["input"],
    legacy_only: &[],
    live_contract: None,
    grammar: Grammar {
        required: &[],
        optional: &["input"],
        groups: &[],
    },
    adapt: no_dependencies,
}];

fn no_dependencies(_record: &Record, _index: &MetaIndex) -> Result<ObjectDeps, String> {
    Ok(ObjectDeps::new())
}

/// The adapter for a (kind, schema) pair. Kinds whose producer never wrote a
/// `schema` input match only `None`, so a record that carries an unexpected
/// schema value can never share a path with one that does not.
///
/// The kernel never names a tailor: the layer above installs the tailors'
/// rows once at startup (`tailors::install_kinds`, called by
/// `commands::dispatch`). A kind that was never installed has no adapter,
/// which fails closed: gc refuses to sweep a store whose records it cannot
/// read, exactly as for an unknown kind.
fn registered_kinds() -> impl Iterator<Item = &'static KindAdapter> {
    let rows = KERNEL_KINDS.iter().chain(installed_kinds().iter().copied());
    #[cfg(test)]
    {
        rows.chain(TEST_KINDS.iter())
    }
    #[cfg(not(test))]
    {
        rows
    }
}

fn adapter_for(kind: &str, schema: Option<&str>) -> Option<&'static KindAdapter> {
    registered_kinds().find(|adapter| adapter.kind == kind && adapter.schema == schema)
}

static INSTALLED_KINDS: OnceLock<Vec<&'static KindAdapter>> = OnceLock::new();

fn kind_schema_set(
    rows: &[&'static KindAdapter],
) -> BTreeSet<(&'static str, Option<&'static str>)> {
    rows.iter().map(|row| (row.kind, row.schema)).collect()
}

/// Install the object-kind rows the kernel may adapt beyond its own. The
/// first call wins. A repeated identical installation is a no-op, while a
/// different (kind, schema) set is a programming error.
pub(crate) fn install_kinds(rows: impl IntoIterator<Item = &'static KindAdapter>) {
    let rows: Vec<_> = rows.into_iter().collect();
    let installed = INSTALLED_KINDS.get_or_init(|| rows.clone());
    let installed_pairs = kind_schema_set(installed);
    let new_pairs = kind_schema_set(&rows);
    if installed_pairs != new_pairs {
        panic!(
            "object-kind rows already installed with a different (kind, schema) set: installed={installed_pairs:?}, new={new_pairs:?}"
        );
    }
}

fn installed_kinds() -> &'static [&'static KindAdapter] {
    #[cfg(test)]
    tests::install_shipped_kinds();
    INSTALLED_KINDS.get().map(Vec::as_slice).unwrap_or(&[])
}

fn no_adapter_reason(kind: &str, schema: Option<&str>) -> String {
    match schema {
        Some(schema) => format!(
            "no adapter covers schema {schema} of kind {kind}; this layout was never shipped by \
             a known producer, so its dependency set cannot be reconstructed"
        ),
        None => format!(
            "no adapter covers kind {kind} without a schema input; its dependency set cannot be \
             reconstructed"
        ),
    }
}

/// Enforce `grammar` mechanically: every required input present, no
/// unrecognized input, and every group's sibling pairing complete. The
/// message always names the offending field so an operator can diff the
/// record against the producer's grammar.
fn enforce_grammar(inputs: &BTreeMap<String, String>, grammar: &Grammar) -> Result<(), String> {
    for key in grammar.required {
        if !inputs.contains_key(*key) {
            return Err(format!(
                "identity has no {key} input; the producer writes it on every commit, so this \
                 record is incomplete and cannot be certified"
            ));
        }
    }
    for key in inputs.keys() {
        if grammar_accepts_key(grammar, key) {
            continue;
        }
        return Err(format!(
            "unrecognized identity input {key}; a pinned-producer record may only carry inputs \
             its grammar defines, so this layout cannot be certified"
        ));
    }
    for (prefix, siblings) in grammar.groups {
        let Some(siblings) = siblings else { continue };
        let suffixes: Vec<&str> = inputs
            .keys()
            .filter_map(|key| key.strip_prefix(prefix))
            .collect();
        for suffix in suffixes {
            for sibling in *siblings {
                if !inputs.contains_key(&format!("{sibling}{suffix}")) {
                    return Err(format!(
                        "identity has {prefix}{suffix} but no {sibling}{suffix}; the producer \
                         writes both, so this record is incomplete and cannot be certified"
                    ));
                }
            }
        }
    }
    Ok(())
}

/// Whether the migration grammar recognizes one concrete input name. This is
/// also used by the structural live-grammar test so the test and migration
/// path cannot disagree about exact keys versus dynamic prefixes.
pub(crate) fn grammar_accepts_key(grammar: &Grammar, key: &str) -> bool {
    grammar.required.contains(&key)
        || grammar.optional.contains(&key)
        || grammar
            .groups
            .iter()
            .any(|(prefix, _)| key.starts_with(prefix))
}

/// Enforce the current producer's publication grammar. Unlike migration,
/// this intentionally does not use `Grammar`: its required fields describe
/// only what the live producer writes today, and its optional entries may be
/// exact keys or dynamic prefixes.
fn enforce_live_grammar(identity: &Identity, adapter: &KindAdapter) -> Result<(), String> {
    let inputs = &identity.inputs;
    for key in adapter.live_required {
        if !inputs.contains_key(*key) {
            return Err(format!(
                "identity has no live-required {key} input; the current producer writes it on every commit"
            ));
        }
    }
    for key in inputs.keys() {
        let allowed = adapter.live_required.contains(&key.as_str())
            || adapter.live_optional.contains(&key.as_str())
            || adapter
                .live_optional
                .iter()
                .any(|prefix| prefix.ends_with(':') && key.starts_with(prefix));
        if !allowed {
            return Err(format!(
                "unrecognized live identity input {key}; the current producer's live grammar does not write it"
            ));
        }
    }
    platform_of(identity)?;
    Ok(())
}

/// Check a *live* identity against its producer's grammar row.
///
/// Each row describes what its producer builds today, but until now the only
/// reader of a row was `adapt_inner`, the legacy-record migration path. A
/// producer that started writing a new input, or stopped writing a required
/// one, committed fine; the stale row bit much later, during a migration, on
/// a store nobody could re-create. This closes that gap by reading the row at
/// commit time.
///
/// A kind absent from every row is refused. This closes the typo path where a
/// producer can commit a kind such as `cpythno` without any grammar at all.
pub(crate) fn check_identity_grammar(identity: &Identity) -> Result<(), String> {
    let schema = schema_input_of(identity);
    match adapter_for(&identity.kind, schema) {
        Some(adapter) => {
            if let Some(successor) = adapter.superseded_by {
                return Err(format!(
                    "kind {}, schema {schema:?} is superseded by {successor}; the current \
                     producer must publish the successor identity. This row is kept only so \
                     records already in the store still migrate",
                    identity.kind
                ));
            }
            enforce_live_grammar(identity, adapter)?;
            if let Some(contract) = adapter.live_contract {
                contract(identity)?;
            }
            Ok(())
        }
        None => {
            let rows: Vec<&KindAdapter> = registered_kinds()
                .filter(|adapter| adapter.kind == identity.kind)
                .collect();
            if !rows.is_empty() {
                let schemas: Vec<Option<&str>> = rows.iter().map(|row| row.schema).collect();
                return Err(format!(
                    "identity kind {} has schema {:?}, but its grammar rows list schemas {:?}",
                    identity.kind, schema, schemas
                ));
            }
            Err(format!(
                "identity kind {} has no registered object-kind grammar row",
                identity.kind
            ))
        }
    }
}

/// Can this identity only have come from an older tog, never from a live
/// commit? True for a kind with no row at all and for a superseded schema.
///
/// Narrow on purpose: an identity whose kind and schema are both current but
/// whose inputs are wrong is a mistake in the fixture, and its caller should
/// keep failing at the commit guard rather than quietly taking the
/// write-by-hand path.
#[cfg(test)]
pub(crate) fn is_historical_only(identity: &Identity) -> bool {
    match adapter_for(&identity.kind, schema_input_of(identity)) {
        Some(adapter) => adapter.superseded_by.is_some(),
        None => !registered_kinds().any(|adapter| adapter.kind == identity.kind),
    }
}

fn adapt_inner(record: &Record, index: &MetaIndex) -> Result<ObjectDeps, String> {
    let kind = record.identity.kind.as_str();
    let schema = record.schema_input();
    // Fail closed before any derivation: a record that does not match its
    // producer's full grammar is incomplete evidence, and an adapter must
    // never certify a partial set.
    let adapter = adapter_for(kind, schema).ok_or_else(|| no_adapter_reason(kind, schema))?;
    enforce_grammar(&record.identity.inputs, &adapter.grammar)?;
    (adapter.adapt)(record, index)
}

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Algo {
    Sha256,
    Sha512,
}

impl Algo {
    fn name(self) -> &'static str {
        match self {
            Algo::Sha256 => "sha256",
            Algo::Sha512 => "sha512",
        }
    }
}

pub(crate) fn input<'a>(record: &'a Record, key: &str) -> Result<&'a str, String> {
    record
        .identity
        .inputs
        .get(key)
        .map(String::as_str)
        .ok_or_else(|| format!("identity has no {key} input"))
}

pub(crate) fn add_digest(
    deps: &mut ObjectDeps,
    algo: Algo,
    hex: &str,
    what: &str,
) -> Result<(), String> {
    let digest = parse_digest(algo.name(), hex).map_err(|reason| format!("{what}: {reason}"))?;
    deps.cache_digest(digest);
    Ok(())
}

/// Record an object dependency, proving the object still has a record.
///
/// A reference to an object this store no longer holds is *not* a downgrade
/// opportunity: the historical build input was collected by an older sweep,
/// so the evidence needed to certify this record is simply gone.
pub(crate) fn add_object(
    deps: &mut ObjectDeps,
    id: &str,
    index: &MetaIndex,
    what: &str,
) -> Result<(), String> {
    if !store::is_object_id(id) {
        return Err(format!("{what} is not a store object id: {id:?}"));
    }
    if !index.contains(id) {
        return Err(format!(
            "{what} names object {id}, which this store no longer has metadata for"
        ));
    }
    deps.object_id(id)
        .map_err(|error| format!("{what}: {error}"))?;
    Ok(())
}

/// A pinned artifact realized on its own: no object dependencies, one
/// algorithm-qualified digest named directly by the identity.
pub(crate) fn artifact_only(record: &Record, key: &str, algo: Algo) -> Result<ObjectDeps, String> {
    let mut deps = ObjectDeps::new();
    add_digest(&mut deps, algo, input(record, key)?, key)?;
    Ok(deps)
}

/// The one-artifact rows every toolchain tailor shares.
pub(crate) fn artifact_sha256(record: &Record, _index: &MetaIndex) -> Result<ObjectDeps, String> {
    artifact_only(record, "artifact_sha256", Algo::Sha256)
}

pub(crate) fn artifact_sha512(record: &Record, _index: &MetaIndex) -> Result<ObjectDeps, String> {
    artifact_only(record, "artifact_sha512", Algo::Sha512)
}

/// Build an index from records the caller constructed, for adapter fixtures
/// and for the drift checks each producer module keeps next to its own
/// identity function.

#[cfg(test)]
pub(crate) fn index_of(records: Vec<Record>) -> MetaIndex {
    let mut entries = BTreeMap::new();
    for record in records {
        entries.insert(record.id.clone(), record);
    }
    MetaIndex { entries }
}

/// A legacy record for `identity`, as a store written before
/// `object-meta/2` would hold it.
#[cfg(test)]
pub(crate) fn legacy_record(identity: Identity) -> Record {
    Record {
        id: identity.object_id(),
        identity,
        evidence: Evidence::Legacy,
        dependencies: BTreeSet::new(),
        cache: BTreeSet::new(),
        had_legacy_refs: true,
        value: serde_json::json!({}),
    }
}

/// Adapt `identity` against an index that also contains `others`.
#[cfg(test)]
pub(crate) fn adapt_identity_for_test(identity: Identity, others: Vec<Record>) -> Adaptation {
    let record = legacy_record(identity);
    let mut records = others;
    records.push(record.clone());
    adapt(&record, &index_of(records))
}

