    /// `(dependency ids, "algo:hex" digests)` of a proven adaptation.
    fn proven(identity: Identity, others: Vec<Record>) -> (Vec<String>, Vec<String>) {
        match adapt_identity_for_test(identity, others) {
            Adaptation::Proven(deps) => (
                deps.objects.iter().cloned().collect(),
                deps.cache
                    .iter()
                    .map(|digest| format!("{}:{}", digest.algo(), digest.hex()))
                    .collect(),
            ),
            Adaptation::Unresolved(reason) => panic!("expected a proven adaptation: {reason}"),
        }
    }

    fn unresolved(identity: Identity, others: Vec<Record>) -> String {
        match adapt_identity_for_test(identity, others) {
            Adaptation::Unresolved(reason) => reason,
            Adaptation::Proven(deps) => {
                panic!("expected a refusal, got {:?}", deps.objects)
            }
        }
    }

    fn hex(byte: char, len: usize) -> String {
        std::iter::repeat_n(byte, len).collect()
    }

    fn sha256(byte: char) -> String {
        hex(byte, 64)
    }

    fn sha512(byte: char) -> String {
        hex(byte, 128)
    }

    fn sha1(byte: char) -> String {
        hex(byte, 40)
    }

    /// A store object id with a recognisable suffix.
    fn oid(byte: char, suffix: &str) -> String {
        format!("{}-{suffix}", hex(byte, 40))
    }

