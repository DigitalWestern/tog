//! Object metadata: the `object-meta/2` record, its read-only index, and the
//! pure per-kind/per-schema adapters that upgrade a legacy record.
//!
//! An adapter is a pure function of one validated legacy record plus a
//! read-only index of the other records in the store. It returns
//! `Proven(ObjectDeps)` — the exact set the producer of that record would
//! supply today — or `Unresolved(reason)`. It never reads the network, never
//! runs a package manager or a build, and never falls back on a current
//! default pin: everything it certifies is derived from the record's own
//! identity inputs, or from another record it matched exactly.
//!
//! The old inferred `refs` array is never evidence of completeness. It was
//! generated by scanning identity inputs for anything that looked like an
//! object id (`store::object_refs`), so it can be both incomplete (an
//! indirect reference recorded as a fingerprint) and over-broad. Adapters
//! reconstruct the set from the producer's own input grammar instead.

use crate::kernel::fetch::Digest;
use crate::kernel::store::{self, ObjectDeps};
use crate::kernel::types::Identity;
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::io;
use std::path::Path;

/// The result of adapting one legacy record.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Adaptation {
    /// The exact dependency set the producer would supply for this identity.
    Proven(ObjectDeps),
    /// The record cannot be certified. The string names the kind, the schema
    /// and what is missing, so the operator can act on it.
    Unresolved(String),
}

/// What a stored record claims about how its dependency set was obtained.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Evidence {
    /// Pre-`object-meta/2`: no dependency evidence at all.
    Legacy,
    /// Supplied by the realization caller at commit time.
    Explicit,
    /// Derived from a legacy record by the named adapter version.
    Adapted(String),
}

/// One parsed metadata record. Reading never touches object mtimes.
#[derive(Debug, Clone)]
pub struct Record {
    pub id: String,
    pub identity: Identity,
    pub evidence: Evidence,
    /// Empty for a legacy record: it has no proven dependencies.
    pub dependencies: BTreeSet<String>,
    pub cache: BTreeSet<Digest>,
    /// The legacy record carried a `refs` array. This is *not* completeness
    /// evidence; it is the pre-D retention boundary that `--collect-legacy`
    /// keys on, and migration must preserve it.
    pub had_legacy_refs: bool,
    /// The whole record, so migration can rewrite it without inventing or
    /// dropping unrelated fields (`created`, `exceptions`, ...).
    pub value: serde_json::Value,
}

impl Record {
    pub fn schema_input(&self) -> Option<&str> {
        self.identity.inputs.get("schema").map(String::as_str)
    }

    /// The kind/schema pair used for adapter dispatch and for diagnostics.
    /// Kinds whose producer never wrote a `schema` input dispatch on the
    /// kind alone; they are listed explicitly in `adapt` so a record that
    /// unexpectedly carries one is refused instead of silently sharing a
    /// path with a different schema.
    pub fn describe(&self) -> String {
        match self.schema_input() {
            Some(schema) => format!("kind {}, schema {schema}", self.identity.kind),
            None => format!("kind {}, no schema input", self.identity.kind),
        }
    }
}

/// A read-only index of every metadata record in the store.
///
/// Adapters use it to resolve indirect references: a producer often commits a
/// *fingerprint* of another object (a version/digest pair, a truncated hash)
/// rather than its id, and the only sound way back to the id is to find the
/// one record whose own identity produces that fingerprint. A missing or
/// ambiguous match is an error, never a guess.
#[derive(Debug, Default, Clone)]
pub struct MetaIndex {
    entries: BTreeMap<String, Record>,
}

impl MetaIndex {
    /// Read and validate every `meta/<id>.json`. Purely a read: no mtime is
    /// refreshed and no object directory is opened.
    pub fn read(store: &store::Store) -> io::Result<MetaIndex> {
        let meta_dir = store.root.join("meta");
        let stat = fs::symlink_metadata(&meta_dir)?;
        if stat.file_type().is_symlink() || !stat.is_dir() {
            return Err(io::Error::new(
                io::ErrorKind::InvalidData,
                "meta is not a real directory",
            ));
        }
        let mut entries = BTreeMap::new();
        for entry in fs::read_dir(&meta_dir)? {
            let entry = entry?;
            let path = entry.path();
            if path.extension().and_then(|ext| ext.to_str()) != Some("json") {
                continue;
            }
            // Every refusal names the record and a command that will list
            // every other unusable record in one pass, so an operator never
            // has to rerun a sweep to discover the next one.
            let record = read_record_at(&path).map_err(|error| {
                io::Error::new(
                    error.kind(),
                    format!(
                        "{error}; nothing can be swept until this record is usable — run \
                         `blanket gc --migrate-metadata` for the full list, then restore or \
                         rebuild the objects it names"
                    ),
                )
            })?;
            entries.insert(record.id.clone(), record);
        }
        Ok(MetaIndex { entries })
    }

    pub fn get(&self, id: &str) -> Option<&Record> {
        self.entries.get(id)
    }

    pub fn iter(&self) -> impl Iterator<Item = (&String, &Record)> {
        self.entries.iter()
    }

    pub fn len(&self) -> usize {
        self.entries.len()
    }

    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    pub fn contains(&self, id: &str) -> bool {
        self.entries.contains_key(id)
    }

    /// Apply proposed upgrades in memory.
    ///
    /// A dry run must plan from exactly the records a real sweep would have
    /// published, so it carries its unwritten upgrades forward through this
    /// method instead of re-reading the still-legacy files. The real sweep
    /// applies the same overlay over records it has just written, which is a
    /// no-op — that is the point: one code path, one set of evidence.
    pub fn apply(&mut self, upgrades: &BTreeMap<String, serde_json::Value>) -> io::Result<()> {
        for (id, value) in upgrades {
            let record = read_record_value(id, value.clone())?;
            self.entries.insert(id.clone(), record);
        }
        Ok(())
    }

    /// Does the store hold any record that is not already `object-meta/2`?
    pub fn has_legacy(&self) -> bool {
        self.entries
            .values()
            .any(|record| record.evidence == Evidence::Legacy)
    }

    /// The single record of `kind` whose identity satisfies `predicate`.
    ///
    /// Zero matches and more than one match are both errors: an adapter may
    /// not pick a winner, because picking the wrong one certifies a
    /// dependency set that would let GC delete the object actually in use.
    fn unique(
        &self,
        kind: &str,
        what: &str,
        predicate: impl Fn(&Record) -> bool,
    ) -> Result<String, String> {
        let mut found: Vec<&str> = self
            .entries
            .values()
            .filter(|record| record.identity.kind == kind && predicate(record))
            .map(|record| record.id.as_str())
            .collect();
        found.sort_unstable();
        match found.len() {
            1 => Ok(found[0].to_string()),
            0 => Err(format!(
                "no {kind} object in this store matches {what}; the historical build input was \
                 collected by an older sweep and cannot be recovered from metadata"
            )),
            n => Err(format!(
                "{n} {kind} objects match {what} ({}); the reference is ambiguous and must not be guessed",
                found.join(", ")
            )),
        }
    }
}

/// Parse and validate one metadata file. Shared by the index and by the
/// sweep reader so a record can never be understood two different ways.
pub fn read_record_at(path: &Path) -> io::Result<Record> {
    let stat = fs::symlink_metadata(path)?;
    if stat.file_type().is_symlink() || !stat.is_file() {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            format!("object metadata {} is not a regular file", path.display()),
        ));
    }
    let id = path
        .file_stem()
        .and_then(|stem| stem.to_str())
        .ok_or_else(|| {
            io::Error::new(
                io::ErrorKind::InvalidData,
                format!("object metadata name {} is not UTF-8", path.display()),
            )
        })?
        .to_string();
    if !store::is_object_id(&id) {
        return Err(io::Error::new(
            io::ErrorKind::InvalidData,
            format!("object metadata id {id:?} is malformed"),
        ));
    }
    let value: serde_json::Value =
        serde_json::from_reader(fs::File::open(path)?).map_err(|error| {
            io::Error::new(
                io::ErrorKind::InvalidData,
                format!("parse object metadata {}: {error}", path.display()),
            )
        })?;
    read_record_value(&id, value)
}

/// Validate an already-parsed record body against its id.
pub fn read_record_value(id: &str, value: serde_json::Value) -> io::Result<Record> {
    let bad = |message: String| io::Error::new(io::ErrorKind::InvalidData, message);
    let identity_value = value
        .get("identity")
        .cloned()
        .ok_or_else(|| bad(format!("object {id} metadata has no identity")))?;
    let identity: Identity = serde_json::from_value(identity_value)
        .map_err(|error| bad(format!("object {id} has malformed identity: {error}")))?;
    if identity.kind.is_empty() {
        return Err(bad(format!("object {id} metadata has no identity kind")));
    }
    if identity.object_id() != id {
        return Err(bad(format!(
            "object {id} identity hashes to a different object id"
        )));
    }
    if let Some(stored) = value.get("id") {
        if stored.as_str() != Some(id) {
            return Err(bad(format!("object metadata {id} has a mismatched id")));
        }
    }

    let Some(schema_value) = value.get("schema") else {
        // A pre-object-meta/2 record. `refs` is read only to preserve the
        // legacy retention boundary; it is never dependency evidence.
        let had_legacy_refs = value.get("refs").is_some();
        if let Some(refs) = value.get("refs") {
            let refs = refs
                .as_array()
                .ok_or_else(|| bad(format!("object {id} legacy refs is not an array")))?;
            for reference in refs {
                reference
                    .as_str()
                    .ok_or_else(|| bad(format!("object {id} legacy refs contains a non-string")))?;
            }
        }
        return Ok(Record {
            id: id.to_string(),
            identity,
            evidence: Evidence::Legacy,
            dependencies: BTreeSet::new(),
            cache: BTreeSet::new(),
            had_legacy_refs,
            value,
        });
    };

    let schema = schema_value
        .as_str()
        .ok_or_else(|| bad(format!("object {id} has an invalid metadata schema")))?;
    if schema != "object-meta/2" {
        return Err(bad(format!(
            "object {id} has unknown metadata schema {schema}"
        )));
    }
    let mut dependencies = BTreeSet::new();
    for dependency in value
        .get("dependencies")
        .and_then(serde_json::Value::as_array)
        .ok_or_else(|| bad(format!("object {id} metadata has no explicit dependencies")))?
    {
        let dependency = dependency
            .as_str()
            .ok_or_else(|| bad(format!("object {id} has a non-string dependency")))?;
        if !store::is_object_id(dependency) || !dependencies.insert(dependency.to_string()) {
            return Err(bad(format!(
                "object {id} has a malformed or duplicate dependency {dependency:?}"
            )));
        }
    }
    let mut cache = BTreeSet::new();
    for digest in value
        .get("cache_digests")
        .and_then(serde_json::Value::as_array)
        .ok_or_else(|| {
            bad(format!(
                "object {id} metadata has no explicit cache digests"
            ))
        })?
    {
        let object = digest
            .as_object()
            .ok_or_else(|| bad(format!("object {id} has a malformed cache digest")))?;
        let algo = object
            .get("algo")
            .and_then(serde_json::Value::as_str)
            .ok_or_else(|| bad(format!("object {id} cache digest has no algorithm")))?;
        let hex = object
            .get("hex")
            .and_then(serde_json::Value::as_str)
            .ok_or_else(|| bad(format!("object {id} cache digest has no hex")))?;
        let digest = parse_digest(algo, hex)
            .map_err(|reason| bad(format!("object {id} cache digest: {reason}")))?;
        if !cache.insert(digest) {
            return Err(bad(format!("object {id} has a duplicate cache digest")));
        }
    }
    let evidence = value
        .get("evidence")
        .and_then(serde_json::Value::as_str)
        .ok_or_else(|| bad(format!("object {id} metadata has no evidence marker")))?;
    let evidence = if evidence == "explicit" {
        Evidence::Explicit
    } else if let Some(rest) = evidence.strip_prefix("adapted:") {
        if rest.is_empty() {
            return Err(bad(format!("object {id} has an empty adapted marker")));
        }
        Evidence::Adapted(rest.to_string())
    } else {
        return Err(bad(format!(
            "object {id} has unknown evidence marker {evidence}"
        )));
    };
    // Migration preserves the pre-D retention boundary explicitly: a record
    // that never carried `refs` keeps its legacy retention after upgrade,
    // because proving an object's outgoing dependencies says nothing about
    // whether some pre-registry project still needs the object itself.
    let had_legacy_refs = evidence == Evidence::Explicit
        || !value
            .get("legacy_retention")
            .and_then(serde_json::Value::as_bool)
            .unwrap_or(false);
    Ok(Record {
        id: id.to_string(),
        identity,
        evidence,
        dependencies,
        cache,
        had_legacy_refs,
        value,
    })
}

fn parse_digest(algo: &str, hex: &str) -> Result<Digest, String> {
    let digest = match algo {
        "sha1" => Digest::sha1(hex),
        "sha256" => Digest::sha256(hex),
        "sha512" => Digest::sha512(hex),
        other => return Err(format!("unsupported cache algorithm {other}")),
    };
    digest.map_err(|error| error.to_string())
}

// ---------------------------------------------------------------------------
// Adapters
//
// Each adapter reconstructs the dependency set the producer of that record
// builds today, from the producer's own input grammar. The pairing is
// deliberate: `adapt` must return exactly what `commit_with_deps` would be
// given for the same identity, or a migrated store stops being syncable —
// `store::validate_cached_dependency_evidence` turns every later cache hit on
// a divergent record into a hard error.
//
// The coverage matrix in ARCHITECTURE.md lists every row implemented here.
// ---------------------------------------------------------------------------

/// The adapter version stamped into `evidence: "adapted:<kind>@<version>"`.
/// Bump a kind's version when its reconstruction changes meaning, so an old
/// adapted record is distinguishable from a new one.
pub fn adapter_version(_kind: &str) -> u32 {
    1
}

/// Adapt one legacy record. Pure: the only inputs are the record and the
/// index, and the only outputs are a proven set or a named reason.
pub fn adapt(record: &Record, index: &MetaIndex) -> Adaptation {
    if record.evidence != Evidence::Legacy {
        return Adaptation::Unresolved(format!(
            "{}: record is already object-meta/2 and is not a migration candidate",
            record.describe()
        ));
    }
    match adapt_inner(record, index) {
        Ok(deps) => Adaptation::Proven(deps),
        Err(reason) => Adaptation::Unresolved(format!("{}: {reason}", record.describe())),
    }
}

/// The input grammar one producer writes for a (kind, schema) pair.
///
/// `required` inputs are written unconditionally at every commit; `optional`
/// inputs are written only in some shapes. Anything else must match one of
/// `groups`' prefixes. A record that misses a required input, carries an
/// unrecognized input, or breaks a group's pairing is incomplete evidence and
/// is refused — the same conservative principle as the containment guard,
/// applied per field: never certify less than the producer demonstrably
/// wrote.
struct Grammar {
    required: &'static [&'static str],
    optional: &'static [&'static str],
    /// Recognized dynamic key prefixes. Each entry may demand sibling
    /// prefixes for the same suffix (`("raw:", Some(&["pkg:"]))` means every
    /// `raw:<name>` input requires a `pkg:<name>` input and vice versa).
    groups: &'static [(&'static str, Option<&'static [&'static str]>)],
}

fn no_adapter_reason(kind: &str, schema: Option<&str>) -> String {
    match schema {
        Some(schema) => format!(
            "no adapter covers schema {schema} of kind {kind}; this layout was never shipped by \
             a known producer, so its dependency set cannot be reconstructed"
        ),
        None => format!(
            "no adapter covers kind {kind} without a schema input; its dependency set cannot be \
             reconstructed"
        ),
    }
}

/// The grammar table for all supported (kind, schema) pairs, derived from the
/// producers' identity functions. A pair missing here is refused by
/// `no_adapter_reason`, never adapted.
fn grammar_for(kind: &str, schema: Option<&str>) -> Option<Grammar> {
    let platform = &["platform"][..];
    let grammar = match (kind, schema) {
        ("cpython", None) | ("uv", None) | ("nodejs", None) => Grammar {
            required: &["artifact_sha256"],
            optional: platform,
            groups: &[],
        },
        ("go", Some("go-toolchain/1")) | ("ruby", Some("ruby-toolchain/1")) => Grammar {
            required: &["schema", "artifact_sha256"],
            optional: platform,
            groups: &[],
        },
        ("dotnet-sdk", Some("dotnet-sdk/1")) => Grammar {
            required: &["schema", "artifact_sha512"],
            optional: platform,
            groups: &[],
        },
        ("rust", Some("rust-toolchain/1")) => Grammar {
            required: &["schema", "cargo_sha256", "rust_std_sha256", "rustc_sha256"],
            optional: platform,
            groups: &[],
        },
        ("beam", Some("beam-toolchain/1")) => Grammar {
            required: &[
                "schema",
                "otp_sha256",
                "elixir_sha256",
                "hex_sha512",
                "rebar3_sha512",
            ],
            optional: &["platform", "versions", "relocation_schema", "store_root"],
            groups: &[],
        },
        ("git-source", Some("git-source/2")) => Grammar {
            required: &["schema", "url", "commit"],
            optional: &[],
            groups: &[],
        },
        ("native-libs", None) => Grammar {
            required: &["platform", "manifest_sha256"],
            optional: &["store_root"],
            groups: &[],
        },
        ("rustfmt", Some("rustfmt/1")) => Grammar {
            required: &["schema", "rust_object", "rustfmt_sha256"],
            optional: platform,
            groups: &[],
        },
        ("cargo-vendor", Some("cargo-vendor/1")) => Grammar {
            required: &["schema"],
            optional: &[],
            groups: &[("crate:", None)],
        },
        ("go-modcache", Some("go-modcache/1")) => Grammar {
            required: &["schema", "extractor"],
            optional: &[],
            // The producer writes the mod/modfile/info triplet for every
            // module; a record carrying only part of a triplet is truncated.
            groups: &[
                ("mod:", Some(&["modfile:", "info:"])),
                ("modfile:", Some(&["mod:", "info:"])),
                ("info:", Some(&["mod:", "modfile:"])),
            ],
        },
        ("ruby-gems", Some("ruby-gems/1")) => Grammar {
            required: &["schema", "installer"],
            optional: &["ruby_platform"],
            groups: &[("gem:", None)],
        },
        ("hex-deps", Some("hex-deps/1")) => Grammar {
            required: &["schema", "beam"],
            optional: &[],
            groups: &[("dep:", None)],
        },
        ("nuget-packages", Some("nuget-packages/1")) => Grammar {
            required: &["schema", "extractor"],
            optional: &[],
            // NuGet always writes the pkg/raw pair per package; `pkg:` is
            // NuGet's own content hash (not a cache address) and `raw:` is
            // the cached `.nupkg` digest. Either alone is a truncated record.
            groups: &[("raw:", Some(&["pkg:"])), ("pkg:", Some(&["raw:"]))],
        },
        ("node-env", Some("node-env/3")) => Grammar {
            required: &["schema", "nodejs"],
            optional: &["store_root", "layout", "workspaces", "native_libs"],
            groups: &[("pkg:", None), ("provisioned:", None), ("artifact:", None)],
        },
        ("python-env", Some("python-env/2")) => Grammar {
            required: &["schema", "cpython"],
            optional: &["store_root", "native_libs"],
            groups: &[("pkg:", None)],
        },
        ("sdist-build", Some("sdist-build/2")) => Grammar {
            required: &["schema", "sdist_sha256", "python", "platform", "toolchain"],
            optional: &[],
            groups: &[],
        },
        ("sdist-build", Some("sdist-build/3")) => Grammar {
            required: &["schema", "sdist_sha256", "python", "platform", "build_env"],
            optional: &["rust", "vendor", "native_libs", "native_linker"],
            groups: &[],
        },
        _ => return None,
    };
    Some(grammar)
}

/// Enforce `grammar` mechanically: every required input present, no
/// unrecognized input, and every group's sibling pairing complete. The
/// message always names the offending field so an operator can diff the
/// record against the producer's grammar.
fn enforce_grammar(inputs: &BTreeMap<String, String>, grammar: &Grammar) -> Result<(), String> {
    for key in grammar.required {
        if !inputs.contains_key(*key) {
            return Err(format!(
                "identity has no {key} input; the producer writes it on every commit, so this \
                 record is incomplete and cannot be certified"
            ));
        }
    }
    for key in inputs.keys() {
        if grammar.required.contains(&key.as_str()) || grammar.optional.contains(&key.as_str()) {
            continue;
        }
        if grammar
            .groups
            .iter()
            .any(|(prefix, _)| key.starts_with(prefix))
        {
            continue;
        }
        return Err(format!(
            "unrecognized identity input {key}; a pinned-producer record may only carry inputs \
             its grammar defines, so this layout cannot be certified"
        ));
    }
    for (prefix, siblings) in grammar.groups {
        let Some(siblings) = siblings else { continue };
        let suffixes: Vec<&str> = inputs
            .keys()
            .filter_map(|key| key.strip_prefix(prefix))
            .collect();
        for suffix in suffixes {
            for sibling in *siblings {
                if !inputs.contains_key(&format!("{sibling}{suffix}")) {
                    return Err(format!(
                        "identity has {prefix}{suffix} but no {sibling}{suffix}; the producer \
                         writes both, so this record is incomplete and cannot be certified"
                    ));
                }
            }
        }
    }
    Ok(())
}

fn adapt_inner(record: &Record, index: &MetaIndex) -> Result<ObjectDeps, String> {
    let kind = record.identity.kind.as_str();
    let schema = record.schema_input();
    // Fail closed before any derivation: a record that does not match its
    // producer's full grammar is incomplete evidence, and an adapter must
    // never certify a partial set.
    let grammar = grammar_for(kind, schema).ok_or_else(|| no_adapter_reason(kind, schema))?;
    enforce_grammar(&record.identity.inputs, &grammar)?;
    // Dispatch on the (kind, schema) pair. Kinds whose producer never wrote a
    // `schema` input match only `None`, so a record that carries an
    // unexpected schema value can never share a path with one that does not.
    match (kind, record.schema_input()) {
        ("cpython", None) | ("uv", None) | ("nodejs", None) => {
            artifact_only(record, "artifact_sha256", Algo::Sha256)
        }
        ("rust", Some("rust-toolchain/1")) => rust_toolchain(record),
        ("go", Some("go-toolchain/1")) => artifact_only(record, "artifact_sha256", Algo::Sha256),
        ("ruby", Some("ruby-toolchain/1")) => {
            artifact_only(record, "artifact_sha256", Algo::Sha256)
        }
        ("dotnet-sdk", Some("dotnet-sdk/1")) => {
            artifact_only(record, "artifact_sha512", Algo::Sha512)
        }
        ("beam", Some("beam-toolchain/1")) => beam_toolchain(record),
        ("git-source", Some("git-source/2")) => Ok(ObjectDeps::new()),
        ("native-libs", None) => native_libs(record),
        ("rustfmt", Some("rustfmt/1")) => rustfmt(record, index),
        ("cargo-vendor", Some("cargo-vendor/1")) => cargo_vendor(record, index),
        ("go-modcache", Some("go-modcache/1")) => go_modcache(record, index),
        ("ruby-gems", Some("ruby-gems/1")) => ruby_gems(record, index),
        ("hex-deps", Some("hex-deps/1")) => hex_deps(record, index),
        ("nuget-packages", Some("nuget-packages/1")) => nuget_packages(record, index),
        ("node-env", Some("node-env/3")) => node_env_v3(record, index),
        ("python-env", Some("python-env/2")) => python_env_v2(record, index),
        ("sdist-build", Some("sdist-build/2")) => sdist_build_v2(record, index),
        ("sdist-build", Some("sdist-build/3")) => sdist_build_v3(record, index),
        (kind, Some(schema)) => Err(format!(
            "no adapter covers schema {schema} of kind {kind}; this layout was never shipped by a \
             known producer, so its dependency set cannot be reconstructed"
        )),
        (kind, None) => Err(format!(
            "no adapter covers kind {kind} without a schema input; its dependency set cannot be \
             reconstructed"
        )),
    }
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Algo {
    Sha256,
    Sha512,
}

impl Algo {
    fn name(self) -> &'static str {
        match self {
            Algo::Sha256 => "sha256",
            Algo::Sha512 => "sha512",
        }
    }
}

fn input<'a>(record: &'a Record, key: &str) -> Result<&'a str, String> {
    record
        .identity
        .inputs
        .get(key)
        .map(String::as_str)
        .ok_or_else(|| format!("identity has no {key} input"))
}

fn add_digest(deps: &mut ObjectDeps, algo: Algo, hex: &str, what: &str) -> Result<(), String> {
    let digest = parse_digest(algo.name(), hex).map_err(|reason| format!("{what}: {reason}"))?;
    deps.cache_digest(digest);
    Ok(())
}

/// Record an object dependency, proving the object still has a record.
///
/// A reference to an object this store no longer holds is *not* a downgrade
/// opportunity: the historical build input was collected by an older sweep,
/// so the evidence needed to certify this record is simply gone.
fn add_object(
    deps: &mut ObjectDeps,
    id: &str,
    index: &MetaIndex,
    what: &str,
) -> Result<(), String> {
    if !store::is_object_id(id) {
        return Err(format!("{what} is not a store object id: {id:?}"));
    }
    if !index.contains(id) {
        return Err(format!(
            "{what} names object {id}, which this store no longer has metadata for"
        ));
    }
    deps.object_id(id)
        .map_err(|error| format!("{what}: {error}"))?;
    Ok(())
}

/// A pinned artifact realized on its own: no object dependencies, one
/// algorithm-qualified digest named directly by the identity.
fn artifact_only(record: &Record, key: &str, algo: Algo) -> Result<ObjectDeps, String> {
    let mut deps = ObjectDeps::new();
    add_digest(&mut deps, algo, input(record, key)?, key)?;
    Ok(deps)
}

/// `rust-toolchain/1`: the three components the producer merges, each named
/// by its own identity input. `cargo::rust_components` requires exactly
/// cargo + rust-std + rustc, which is what the identity commits to.
fn rust_toolchain(record: &Record) -> Result<ObjectDeps, String> {
    let mut deps = ObjectDeps::new();
    for key in ["cargo_sha256", "rust_std_sha256", "rustc_sha256"] {
        add_digest(&mut deps, Algo::Sha256, input(record, key)?, key)?;
    }
    Ok(deps)
}

/// `beam-toolchain/1`: OTP and Elixir by sha256, Hex and rebar3 by sha512.
/// All four are direct identity inputs; the `versions` and relocation inputs
/// are not artifacts.
fn beam_toolchain(record: &Record) -> Result<ObjectDeps, String> {
    let mut deps = ObjectDeps::new();
    for (key, algo) in [
        ("otp_sha256", Algo::Sha256),
        ("elixir_sha256", Algo::Sha256),
        ("hex_sha512", Algo::Sha512),
        ("rebar3_sha512", Algo::Sha512),
    ] {
        add_digest(&mut deps, algo, input(record, key)?, key)?;
    }
    Ok(deps)
}

/// `native-libs`: the identity commits to a *digest of the package manifest*,
/// never to the individual library digests, so they cannot be read out of the
/// record. They are recovered only when the pinned table still hashes to the
/// recorded manifest digest — that is a verified match against the record's
/// own evidence, not a current-default guess. A libset from a different pin
/// set is unresolved.
///
/// The rejected first implementation instead matched the key name
/// `manifest_sha256` and emitted the manifest hash itself as a cache digest,
/// fabricating a digest for a file that never existed in the cache.
fn native_libs(record: &Record) -> Result<ObjectDeps, String> {
    if record.identity.version != crate::tailors::python::nativelibs::NATIVE_LIBS_VERSION {
        return Err(format!(
            "libset version {} predates the pinned manifest this build knows (v{}); its library \
             digests are not recoverable from metadata",
            record.identity.version,
            crate::tailors::python::nativelibs::NATIVE_LIBS_VERSION
        ));
    }
    let recorded = input(record, "manifest_sha256")?;
    let platform_input = input(record, "platform")?;
    let platform = crate::kernel::platform::Platform::ALL
        .iter()
        .find(|platform| platform.triple() == platform_input)
        .ok_or_else(|| format!("unknown platform {platform_input}"))?;
    let manifest = crate::tailors::python::nativelibs::manifest_sha256(*platform)
        .map_err(|error| format!("no pinned library manifest for {platform_input}: {error}"))?;
    if manifest != recorded {
        return Err(format!(
            "the pinned library manifest for {platform_input} hashes to {manifest}, not the \
             recorded {recorded}; the library digests for this object are not recoverable"
        ));
    }
    let mut deps = ObjectDeps::new();
    for sha256 in crate::tailors::python::nativelibs::pinned_package_digests(*platform)
        .map_err(|error| format!("pinned library set: {error}"))?
    {
        add_digest(&mut deps, Algo::Sha256, &sha256, "pinned library")?;
    }
    Ok(deps)
}

/// `rustfmt/1`: the paired Rust object is a direct identity input, and the
/// component tarball is its own sha256. `rustfmt/1` symlinks `lib` into the
/// Rust object, so the pairing is a real filesystem dependency.
fn rustfmt(record: &Record, index: &MetaIndex) -> Result<ObjectDeps, String> {
    let mut deps = ObjectDeps::new();
    add_object(
        &mut deps,
        input(record, "rust_object")?,
        index,
        "rust_object",
    )?;
    add_digest(
        &mut deps,
        Algo::Sha256,
        input(record, "rustfmt_sha256")?,
        "rustfmt_sha256",
    )?;
    Ok(deps)
}

/// `cargo-vendor/1`: one entry per crate. A registry crate contributes its
/// `.crate` sha256; a git crate contributes the realized `git-source` object.
///
/// The Rust toolchain is deliberately **not** a dependency of a vendor tree.
/// `cargo::realize_vendor_inner` runs only `tar`; no part of the toolchain is
/// a build input, and the vendor identity does not commit to one — so
/// recording it would make the same identity publishable with two different
/// dependency sets. See the deviation note in the ARCHITECTURE.md matrix.
fn cargo_vendor(record: &Record, index: &MetaIndex) -> Result<ObjectDeps, String> {
    let mut deps = ObjectDeps::new();
    for (key, value) in &record.identity.inputs {
        let Some(krate) = key.strip_prefix("crate:") else {
            if key == "schema" {
                continue;
            }
            return Err(format!("unexpected identity input {key}"));
        };
        match value.strip_prefix("git:") {
            Some(id) => add_object(&mut deps, id, index, &format!("crate {krate}"))?,
            None => add_digest(&mut deps, Algo::Sha256, value, &format!("crate {krate}"))?,
        }
    }
    Ok(deps)
}

/// `go-modcache/1`: the extractor is a `go<version>:<sha256>` fingerprint, so
/// the Go toolchain object is found by matching the one `go` record with that
/// version and artifact digest. Each module contributes three cached files.
fn go_modcache(record: &Record, index: &MetaIndex) -> Result<ObjectDeps, String> {
    let extractor = input(record, "extractor")?;
    let (version, sha256) = extractor
        .strip_prefix("go")
        .and_then(|rest| rest.split_once(':'))
        .ok_or_else(|| {
            format!("extractor {extractor:?} is not a go<version>:<sha256> reference")
        })?;
    let go = index.unique(
        "go",
        &format!("Go {version} built from artifact {sha256}"),
        |candidate| {
            candidate.identity.version == version
                && candidate
                    .identity
                    .inputs
                    .get("artifact_sha256")
                    .map(String::as_str)
                    == Some(sha256)
        },
    )?;
    let mut deps = ObjectDeps::new();
    add_object(&mut deps, &go, index, "extractor")?;
    for (key, value) in &record.identity.inputs {
        if let Some(module) = key.strip_prefix("mod:") {
            // "<h1 hash>:<zip sha256>"; the h1 hash itself contains a colon.
            let (_, zip) = value
                .rsplit_once(':')
                .ok_or_else(|| format!("module {module} entry {value:?} has no zip digest"))?;
            add_digest(
                &mut deps,
                Algo::Sha256,
                zip,
                &format!("module {module} zip"),
            )?;
        } else if let Some(module) = key.strip_prefix("modfile:") {
            let (_, modfile) = value
                .rsplit_once(':')
                .ok_or_else(|| format!("module {module} go.mod entry {value:?} has no digest"))?;
            add_digest(
                &mut deps,
                Algo::Sha256,
                modfile,
                &format!("module {module} go.mod"),
            )?;
        } else if let Some(module) = key.strip_prefix("info:") {
            add_digest(
                &mut deps,
                Algo::Sha256,
                value,
                &format!("module {module} info"),
            )?;
        } else if key != "schema" && key != "extractor" {
            return Err(format!("unexpected identity input {key}"));
        }
    }
    Ok(deps)
}

